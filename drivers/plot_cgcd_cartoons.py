def _disk_halfheight(
    x: np.ndarray, x_tip: float, x_end: float, h_tip: float,
    h_end: float
) -> np.ndarray:
    """Local half-height of the tapered debris-disk wedge.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        x: Positions along the wedge.
        x_tip: Narrow (blob-side) end.
        x_end: Wide end.
        h_tip: Half-height at the tip.
        h_end: Half-height at the wide end.

    Returns:
        Half-heights at x.
    """
    return h_tip + (h_end - h_tip) * (x - x_tip) / (x_end - x_tip)


def draw_debris_disk(ax) -> None:
    """Tenuous debris disk: tapered wedge with depth, rocks, inflow.

    The disk is a thin wedge, narrowing toward the blob, whose far end
    is capped by a concave arc (a cone seen slightly from the side).
    Depth comes from a diagonal light-to-dark gradient (near/lit edge
    at upper left, far/shadowed edge at lower right).  Small irregular
    rocks float inside; a few are differentiated (red cores).  A black
    arrow marks the disk-to-blob flow.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
    """
    x_tip, x_end = 3.55, 6.35
    h_tip, h_end = 0.035, 0.30
    cap_depth = 0.22

    xs = np.linspace(x_tip, x_end, 120)
    h = _disk_halfheight(xs, x_tip, x_end, h_tip, h_end)
    tt = np.linspace(0.0, np.pi, 60)
    cap = np.column_stack([x_end - cap_depth * np.sin(tt),
                           h_end * np.cos(tt)])
    verts = np.vstack([
        np.column_stack([xs, +h]),
        cap,
        np.column_stack([xs[::-1], -h[::-1]]),
    ])
    clip = Polygon(verts, closed=True, fc="none", ec="none",
                   zorder=4.4)
    ax.add_patch(clip)

    # Diagonal light->dark gradient, clipped to the wedge, for depth.
    nx, ny = 256, 64
    uu, vv = np.meshgrid(np.linspace(0, 1, nx), np.linspace(0, 1, ny))
    t = np.clip(0.65 * uu + 0.35 * vv, 0, 1)
    cl = np.array(to_rgb(DISK_LIGHT_C))
    cd = np.array(to_rgb(DISK_DARK_C))
    img = cl[None, None, :] * (1 - t[..., None]) + \
        cd[None, None, :] * t[..., None]
    im = ax.imshow(
        img, extent=(x_tip, x_end, -h_end, h_end), origin="upper",
        interpolation="bilinear", zorder=4.5
    )
    im.set_clip_path(clip)

    rng = np.random.default_rng(3)
    for _ in range(9):
        x0 = rng.uniform(4.4, 6.0)
        hmax = _disk_halfheight(
            np.array([x0]), x_tip, x_end, h_tip, h_end
        )[0]
        y0 = rng.uniform(-0.65, 0.65) * hmax
        rx, ry = _spot_xy(rng, x0, y0, rng.uniform(0.02, 0.05), n=10)
