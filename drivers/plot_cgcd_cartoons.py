def draw_title(ax, main: str, sub: str) -> None:
    """Dotted-border title box.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
        main: Bold first line.
        sub: Smaller second line.
    """
    # Bottom edge 2 R* above the star center; top flush with YLIM so
    # nothing shows above the box and open lines truncate behind it.
    # clip_on=False: the top edge sits exactly on YLIM's upper bound,
    # so axes-bbox clipping would shave off half of its stroke width;
    # disabling clipping lets the full dashed line render (the sliver
    # that pokes above YLIM lands in the blank margin/gutter).
    x0, y0, w, h = -0.55, 2.0, 4.8, 1.0
    ax.add_patch(Rectangle(
        (x0, y0), w, h, facecolor="white", edgecolor="k", lw=1.0,
        ls=(0, (1, 1.2)), zorder=10, clip_on=False
    ))
    ax.text(x0 + w / 2, y0 + 0.68 * h, main, ha="center", va="center",
            fontsize=11.5, fontweight="bold", zorder=10.2)
    ax.text(x0 + w / 2, y0 + 0.28 * h, sub, ha="center", va="center",
            fontsize=9, zorder=10.2)


def draw_geometry_note(ax) -> None:
    """The 'geometry unlikely' annotation with an elbow arrow.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
    """
    ax.annotate(
        "geometry\nunlikely", xy=(-1.06, 0.05), xytext=(-1.65, -0.85),
        ha="center", va="top", fontsize=8.5, zorder=10,
        arrowprops=dict(
            arrowstyle="->", lw=0.8, color="k",
            connectionstyle="angle,angleA=90,angleB=0",
            shrinkA=2, shrinkB=1,
        ),
    )


def make_panel(ax, key: str, bmode: str = "b_mixed") -> None:
    """Assemble one cartoon panel.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
        key: PANEL_SPECS key ('plasma', 'stardust', 'diskdust').
        bmode: Field-line style ('b_mixed' or 'b_dipole').
    """
    spec = PANEL_SPECS[key]
    ax.set_xlim(XLIM)
    ax.set_ylim(YLIM)
    ax.set_aspect("equal")
    ax.axis("off")

    draw_field_lines(ax, bmode)
    draw_rotation_axis(ax)
    if spec["tube_c"] is not None:
        draw_flux_tube(ax, spec["tube_c"])
    draw_star(ax, spec["spots"])
    if spec["disk"]:
        draw_debris_disk(ax)
    draw_blob(ax, *spec["blob"])
    draw_title(ax, spec["title"], spec["subtitle"])
    if spec["note"]:
        draw_geometry_note(ax)


def main(bmode: str = "b_mixed") -> None:
    """Draw all three panels and save the figure.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        bmode: Field-line style ('b_mixed' or 'b_dipole').
    """
    import os
    os.makedirs(OUTDIR, exist_ok=True)
    set_style("clean")
    _set_fonts(True)
    # Single-column AASTeX layout: three rows, one column.
    fig, axs = plt.subplots(3, 1, figsize=(3.5, 5.55))
    for ax, key in zip(axs, ["plasma", "stardust", "diskdust"]):
        make_panel(ax, key, bmode)
    fig.subplots_adjust(left=0.005, right=0.995, top=0.995,
                        bottom=0.005, hspace=0.03)
    savefig(fig, join(OUTDIR, f"cgcd_cartoons_{bmode}.png"), dpi=400,
            writepdf=1)


