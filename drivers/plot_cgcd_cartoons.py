def dipole_line(
    L: float, r_min: float = 0.55, n: int = 400,
    theta_max: Optional[float] = None, p: float = 2.0,
    tilt_deg: float = 0.0
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """One field line r = L sin^p(theta), optionally tilted.

    theta is the colatitude from the (vertical) rotation axis; only the
    x > 0 half-plane is drawn.  Lines start at r = r_min (inside the
    star, which is drawn on top) so footpoints are hidden by the limb.
    p = 2 is a dipole; p > 2 gives narrower loops.  tilt_deg rotates
    the whole loop about the star center, moving the apex off the
    equator (used for the b_mixed tangled loops).

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        L: Field-line apex radius in stellar radii.
        r_min: Starting radius (buried under the stellar disk).
        n: Number of samples.
        theta_max: Optional colatitude cutoff (e.g. ~pi/2 to draw the
            upper branch only, for the "open" polar lines).
        p: Shape exponent.
        tilt_deg: In-plane rotation of the loop, degrees.

    Returns:
        (theta, x, y) arrays.
    """
    th0 = np.arcsin(min(r_min / L, 1.0) ** (1.0 / p))
    th1 = np.pi - th0 if theta_max is None else theta_max
    theta = np.linspace(th0, th1, n)
    r = L * np.sin(theta) ** p
    x = r * np.sin(theta)
    y = r * np.cos(theta)
    if tilt_deg != 0.0:
        a = np.deg2rad(tilt_deg)
        x, y = x * np.cos(a) - y * np.sin(a), \
            x * np.sin(a) + y * np.cos(a)
    return theta, x, y


def _quad_bezier(
    p0: Tuple[float, float], p1: Tuple[float, float],
    p2: Tuple[float, float], n: int = 200
) -> Tuple[np.ndarray, np.ndarray]:
    """Quadratic Bezier curve through control points.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        p0: Start point.
        p1: Control point.
        p2: End point.
        n: Number of samples.

    Returns:
        (xs, ys) arrays.
    """
    t = np.linspace(0.0, 1.0, n)[:, None]
    pts = ((1 - t) ** 2 * np.array(p0) +
           2 * (1 - t) * t * np.array(p1) +
           t ** 2 * np.array(p2))
    return pts[:, 0], pts[:, 1]


def _gradient_fill(
    ax, shape_fn: Callable[[float], Tuple[np.ndarray, np.ndarray]],
    c_center: str, c_edge: str, n: int = 36, gamma: float = 0.7,
    zorder: float = 3.0
) -> None:
    """Radial gradient via concentric shrinking filled shapes.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
        shape_fn: Maps a scale in (0, 1] to (xs, ys) outline vertices.
        c_center: Color at the center.
        c_edge: Color at the edge.
        n: Number of concentric steps.
        gamma: Exponent on (1 - scale); <1 keeps the center broad.
        zorder: Base zorder.
    """
    ce = np.array(to_rgb(c_edge))
    cc = np.array(to_rgb(c_center))
    for s in np.linspace(1.0, 0.04, n):
        t = (1.0 - s) ** gamma
        col = (1.0 - t) * ce + t * cc
        xs, ys = shape_fn(s)
        ax.fill(xs, ys, color=col, lw=0, zorder=zorder)


def _circle_xy(
    cx: float, cy: float, r: float, n: int = 200
) -> Tuple[np.ndarray, np.ndarray]:
    """Circle outline vertices.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        cx: Center x.
        cy: Center y.
        r: Radius.
        n: Number of samples.

    Returns:
        (xs, ys) arrays.
    """
    t = np.linspace(0, 2 * np.pi, n)
    return cx + r * np.cos(t), cy + r * np.sin(t)


def _blob_xy(
    cx: float, cy: float, a: float, b: float, scale: float = 1.0,
    e: float = 1.6, n: int = 200
) -> Tuple[np.ndarray, np.ndarray]:
    """Rounded-diamond ("spinning top") blob outline.

    A superellipse-like parametrization; exponent e > 1 pinches the
    shape along the axes, mimicking the hand-drawn corotating blob.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        cx: Center x.
        cy: Center y.
        a: Half-width.
        b: Half-height.
        scale: Uniform scale factor (for gradient shells).
        e: Pinch exponent.
        n: Number of samples.

    Returns:
        (xs, ys) arrays.
    """
    t = np.linspace(0, 2 * np.pi, n)
    x = cx + scale * a * np.sign(np.cos(t)) * np.abs(np.cos(t)) ** e
    y = cy + scale * b * np.sign(np.sin(t)) * np.abs(np.sin(t)) ** e
    return x, y


def _spot_xy(
    rng: np.random.Generator, cx: float, cy: float, r0: float,
    n: int = 14
) -> Tuple[np.ndarray, np.ndarray]:
    """Irregular blotchy spot outline.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        rng: Random generator (fixed seed => reproducible art).
        cx: Center x.
        cy: Center y.
        r0: Mean radius.
        n: Number of outline vertices.

    Returns:
        (xs, ys) arrays.
    """
    ang = np.linspace(0, 2 * np.pi, n, endpoint=False)
    raw = rng.uniform(-1.0, 1.0, n)
    sm = (raw + np.roll(raw, 1) + np.roll(raw, -1)) / 3.0
    rad = r0 * (1.0 + 0.5 * sm)
    return cx + rad * np.cos(ang), cy + rad * np.sin(ang)


def _spot_centers_polar(
    rng: np.random.Generator
) -> List[Tuple[float, float, float]]:
    """Spot centers/sizes clustered at both poles (clear mid chord).

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        rng: Random generator.

    Returns:
        List of (x, y, r0) tuples in stellar radii.
    """
    out: List[Tuple[float, float, float]] = []
    for nspot, ysign in [(7, +1), (6, -1)]:
        for _ in range(nspot):
            y0 = ysign * rng.uniform(0.42, 0.88)
            xmax = np.sqrt(max(0.0, 1.0 - y0 ** 2))
            x0 = rng.uniform(-1.0, 1.0) * 0.92 * xmax
            r0 = rng.uniform(0.08, 0.34)
            out.append((x0, y0, r0))
    for _ in range(2):  # a couple of tiny low-latitude stragglers
        y0 = -rng.uniform(0.15, 0.30)
        x0 = rng.uniform(-0.5, 0.5)
        out.append((x0, y0, rng.uniform(0.035, 0.06)))
    out.append((0.68, 0.53, 0.05))  # extra small spot, north-side gap
    return out


def draw_star(ax, spot_mode: str) -> None:
    """Limb-darkened M dwarf with blotchy gray spots.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
        spot_mode: 'polar' (clustered at poles, panel 1) or 'sparse'
            (identical spot set for panels 2 and 3).
    """
    _gradient_fill(
        ax, lambda s: _circle_xy(0.0, 0.0, s), STAR_CENTER_C,
        STAR_EDGE_C, zorder=3.0
    )
    clip = Circle((0, 0), 0.99, fc="none", ec="none", zorder=3.1)
    ax.add_patch(clip)

    if spot_mode == "polar":
        rng = np.random.default_rng(42)
        centers = _spot_centers_polar(rng)
    else:
        rng = np.random.default_rng(7)
        centers = SPARSE_SPOTS
    for (x0, y0, r0) in centers:
        xs, ys = _spot_xy(rng, x0, y0, r0)
        poly = Polygon(
            np.column_stack([xs, ys]), closed=True, fc=SPOT_C,
            ec=SPOT_EDGE_C, lw=0.4, zorder=3.4
        )
        poly.set_clip_path(clip)
        ax.add_patch(poly)

    outline = Circle(
        (0, 0), 1.0, fc="none", ec=STAR_OUTLINE_C, lw=0.8, zorder=3.6
    )
    ax.add_patch(outline)


def draw_field_lines(ax, bmode: str = "b_mixed") -> None:
    """The red field lines (identical in all three panels).

    b_dipole: nested axisymmetric dipole loops plus near-polar upper
    branches that clip at the frame top.  b_mixed: Sun-like tangled
    loops near the star, the two tube-edge lines, and bent open polar
    Beziers; no closed loops beyond the blob.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
        bmode: 'b_mixed' or 'b_dipole'.
    """
    def _line(x: np.ndarray, y: np.ndarray) -> None:
        ax.plot(x, y, color=FIELD_C, lw=0.9, zorder=1.5,
                solid_capstyle="round")

    if bmode == "b_dipole":
        for L in L_CLOSED:
            _, x, y = dipole_line(L)
            _line(x, y)
        for L in L_OPEN:
            _, x, y = dipole_line(L, theta_max=0.52 * np.pi)
            _line(x, y)
        return

    for L in (L_TUBE_IN, L_TUBE_OUT):
        _, x, y = dipole_line(L)
        _line(x, y)
    for (L, tilt, p) in TANGLED_LOOPS:
        _, x, y = dipole_line(L, p=p, tilt_deg=tilt)
        _line(x, y)
    for (p0, p1, p2) in OPEN_BEZIERS:
        x, y = _quad_bezier(p0, p1, p2)
        _line(x, y)


def _flow_arrow(
    ax, theta: np.ndarray, x: np.ndarray, y: np.ndarray,
    th0: float, th1: float, reverse: bool = False
) -> None:
    """Curved black arrow following a field line between two thetas.

    The arrow body is the field-line arc itself, so the flow marker
    bends with the tube; the head sits at the downstream end (th1, or
    th0 if reverse).

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
        theta: Field-line colatitude samples.
        x: Field-line x samples.
        y: Field-line y samples.
        th0: Arc start colatitude.
        th1: Arc end colatitude.
        reverse: If True, the head points toward th0 (used on the
            lower branch, where flow runs against increasing theta).
    """
    sel = (theta >= th0) & (theta <= th1)
    pts = np.column_stack([x[sel], y[sel]])
    if reverse:
        pts = pts[::-1]
    _curved_arrow(ax, pts, lw=1.3, mutation_scale=11, zorder=4.0,
                  head_len=0.16)


def _curved_arrow(
    ax, pts: np.ndarray, lw: float, mutation_scale: float,
    zorder: float, head_len: float = 0.16
) -> None:
    """Curved arrow: body polyline + straight head at the exact end.

    The body is truncated an arclength head_len before the path end,
    i.e. at the base of the head, so the (wider) body line cannot poke
    out of the sides of the head near its tip.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
        pts: (N, 2) polyline, head at pts[-1].
        lw: Line width for body and head edge.
        mutation_scale: Head size.
        zorder: Draw order.
        head_len: Arclength (data units) covered by the head; match
            to ~0.4 * mutation_scale converted to data units.
    """
    d = np.hypot(np.diff(pts[:, 0]), np.diff(pts[:, 1]))
    s = np.concatenate([[0.0], np.cumsum(d)])
    i_cut = int(np.searchsorted(s, s[-1] - head_len))
    i_cut = max(1, min(i_cut, len(pts) - 2))
    ax.plot(pts[:i_cut + 1, 0], pts[:i_cut + 1, 1], color="k", lw=lw,
            zorder=zorder, solid_capstyle="butt")
    arr = FancyArrowPatch(
        tuple(pts[i_cut]), tuple(pts[-1]), arrowstyle="-|>",
        mutation_scale=mutation_scale, lw=lw, color="k",
        zorder=zorder, shrinkA=0, shrinkB=0
    )
    ax.add_patch(arr)


def draw_flux_tube(ax, facecolor: str) -> None:
    """Star-to-blob transport channel: fill, yellow lines, flow arrows.

    The tube is the region between the L_TUBE_IN and L_TUBE_OUT field
    lines; thin gold lines thread it, and black arrows mark the flow
    from the star into the blob along both branches.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
        facecolor: Tube fill color (gray or light red).
    """
    _, xi, yi = dipole_line(L_TUBE_IN)
    _, xo, yo = dipole_line(L_TUBE_OUT)
    verts = np.column_stack([
        np.concatenate([xi, xo[::-1]]),
        np.concatenate([yi, yo[::-1]]),
    ])
    ax.add_patch(Polygon(verts, closed=True, fc=facecolor, ec="none",
                         zorder=1.2))

    for Ly in L_YELLOW:
        _, x, y = dipole_line(Ly)
        ax.plot(x, y, color="gold", lw=0.9, zorder=1.4)

    theta, x, y = dipole_line(L_MID, n=1200)
    for th0, th1, reverse in [
        (0.21 * np.pi, 0.29 * np.pi, False),  # upper, toward blob
        (0.33 * np.pi, 0.40 * np.pi, False),  # descending into blob
        (0.61 * np.pi, 0.685 * np.pi, True),  # lower, toward blob
        (0.71 * np.pi, 0.79 * np.pi, True),   # lower, near the star
    ]:
        _flow_arrow(ax, theta, x, y, th0, th1, reverse)


def draw_rotation_axis(ax) -> None:
    """Dotted rotation axis above the pole with a spin-direction arrow.

    The angular momentum vector points up (+y): the star's left limb
    rotates out of the page, the right limb into it.  The arrow is the
    near-side (lower) half of a circle around the axis, so it sweeps
    left to right with the head at right.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        ax: Target axis.
    """
    ax.plot([0, 0], [1.02, 1.85], color="k", lw=0.8,
            ls="--", zorder=2.5)
    y_c, a, b = 1.70, 0.18, 0.06
    t = np.linspace(1.05 * np.pi, 1.95 * np.pi, 100)
    pts = np.column_stack([a * np.cos(t), y_c + b * np.sin(t)])
    _curved_arrow(ax, pts, lw=0.9, mutation_scale=6, zorder=2.6,
                  head_len=0.09)


