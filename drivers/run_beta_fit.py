"""
Driver for the dip-depth extinction-law (beta) fits.

Fits four models to the multi-band dip-depth dataset (single power law
with shared beta; single power law with independent per-star beta; a
broken power law with a free breakpoint; and a single power law with an
independent beta per dip), compares them by Delta-BIC, and writes the
money plot, per-model QA plots, the beta-violin plot, and the per-dip
beta table and violins. For the "combined" dataset, also writes
results/beta_fit/combined/tab_fitresults_rows.tex: the data rows of
Table 7 ("tab:fitresults") in papers/Bouma_2026_cgcd/beta_fit_summary.tex,
which \input's this file rather than hand-transcribing the fit results.

For the "combined" dataset it also writes a marker-delimited block of
\newcommand's into papers/Bouma_2026_cgcd/ms.tex (like
drivers/calc_fourstar_significant.py): the broken-power-law beta1/beta2
and break wavelength (both sigma_int variants), the single/broken
reduced chi^2, and the single-vs-broken Delta-BIC gap. These feed the
abstract, the "Extinction law results" text, Table tab:fitresults'
footnote (a), the Figure fig:beta caption, and the Conclusions, keeping
those prose numbers in sync with the fit.

Usage:
    python drivers/run_beta_fit.py [options]

    (interactive by default: prompts for row exclusions)

Options:
    --defaults          Use default exclusions; no prompt.
    --include-all       No exclusions.
    --exclude "i,j,k"   Explicit exclusion set (row_ids).
    --refit             Ignore the fit cache and resample.
    --outdir PATH       Override the output directory.
    --no-ms-newcommands Skip writing the ms.tex newcommand block.

Generated by Claude Code on 2026-06-21. Table 7 export added by Claude
Sonnet 5 on 2026-07-04. ms.tex newcommand block added by Claude Opus 4.8
on 2026-07-14.
"""
