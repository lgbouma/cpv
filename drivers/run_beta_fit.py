def default_excluded_row_ids(df_all: pd.DataFrame) -> List[int]:
    """Row ids of the three low-S/N TESS measurements of TIC 262400835.

    Generated by Claude Code on 2026-06-21.

    Args:
        df_all: The full table with a ``row_id`` column.

    Returns:
        Sorted list of default-excluded row ids.
    """
    mask = (df_all["star"] == "TIC 262400835") & (df_all["band"] == "TESS")
    return sorted(int(r) for r in df_all.loc[mask, "row_id"])


def print_row_table(df_all: pd.DataFrame, excluded: Sequence[int]) -> None:
    """Print all rows with a marker on currently-excluded ones.

    Generated by Claude Code on 2026-06-21.

    Args:
        df_all: The full table with a ``row_id`` column.
        excluded: Currently-excluded row ids.
    """
    excl = set(int(e) for e in excluded)
    print("\n row_id  X  star                date_ut                  "
          "band     depth%")
    print(" " + "-" * 74)
    for r in df_all.itertuples():
        mark = "x" if r.row_id in excl else " "
        print(f"  {r.row_id:4d}   {mark}  {r.star:<18.18s} "
              f"{r.date_ut:<22.22s} {r.band:<8.8s} {r.depth_pct:>5.2f}")
    print()


def resolve_exclusions(
    df_all: pd.DataFrame, args: argparse.Namespace
) -> List[int]:
    """Determine the excluded row ids from flags or interactive prompt.

    Generated by Claude Code on 2026-06-21.

    Args:
        df_all: The full table with a ``row_id`` column.
        args: Parsed CLI arguments.

    Returns:
        Sorted list of excluded row ids.
    """
    defaults = default_excluded_row_ids(df_all)

    if args.include_all:
        return []
    if args.exclude is not None:
        return sorted(int(x) for x in args.exclude.split(",") if x.strip())
    if args.defaults:
        return defaults

    # Interactive mode.
    print_row_table(df_all, defaults)
    print(f"Default exclusions (low-S/N TESS of TIC 262400835): {defaults}")
    resp = input(
        "[Enter]/Y = accept defaults, n = include everything, "
        "or comma-separated row_ids to toggle: "
    ).strip()

    if resp == "" or resp.lower() == "y":
        return defaults
    if resp.lower() == "n":
        return []

    toggled = set(defaults)
    for tok in resp.split(","):
        tok = tok.strip()
        if not tok:
            continue
        rid = int(tok)
        toggled.symmetric_difference_update({rid})
    return sorted(toggled)


def collect_ms_newcommands(
    ingredients: Dict[str, Dict]
) -> List[Tuple[str, str, str]]:
    """Build the ms.tex newcommand list from the combined-fit results.

    Reads every value straight out of the same ``ingredients`` dict that
    feeds ``fdb.export_fitresults_table`` (Table tab:fitresults), so the
    prose commands can never drift from the table. ``ingredients[v]`` has
    a ``"broken"`` dict of ``beta1``/``beta2``/``lam_break`` (mean, sd)
    pairs and a ``"bic"`` frame indexed by model (columns
    ``chi2red_meas_err`` and ``dBIC``). Betas/wavelengths and
    ``chi2red_meas_err`` are formatted at 2 dp to match the table's
    ``_fmt_beta``/``_bic_cells``; the single-vs-broken ``dBIC`` gap at
    1 dp to match the Figure fig:beta caption. The gap is
    ``dBIC(single) - dBIC(broken)`` -- both are relative to Model 4, so
    that offset cancels and the difference is the BIC improvement of the
    broken over the single power law.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        ingredients: {"no_sigma_int": ..., "with_sigma_int": ...}, each
            the output of ``fdb.collect_fitresults_ingredients``.

    Returns:
        Ordered list of (command_name, value_str, comment) tuples.
    """
    wi, no = ingredients["with_sigma_int"], ingredients["no_sigma_int"]

    def beta(variant: Dict, which: str) -> Tuple[str, str]:
        mean, sd = variant["broken"][which]
        return f"{mean:.2f}", f"{sd:.2f}"

    def chired(variant: Dict, model: str) -> str:
        return f"{variant['bic'].loc[model, 'chi2red_meas_err']:.2f}"

    def dbic_gap(variant: Dict) -> str:
        bic = variant["bic"]
        gap = bic.loc["shared", "dBIC"] - bic.loc["broken", "dBIC"]
        return f"{gap:.1f}"

    b1_wi, b1u_wi = beta(wi, "beta1")
    b2_wi, b2u_wi = beta(wi, "beta2")
    lb_wi, lbu_wi = beta(wi, "lam_break")
    b1_no, b1u_no = beta(no, "beta1")
    b2_no, b2u_no = beta(no, "beta2")
    lb_no, lbu_no = beta(no, "lam_break")

    return [
        ("brokenbetaone", b1_wi,
         "broken power law beta1 (blueward), with sigma_int [fiducial]"),
        ("brokenbetaoneunc", b1u_wi, "broken beta1 unc, with sigma_int"),
        ("brokenbetatwo", b2_wi,
         "broken power law beta2 (redward), with sigma_int"),
        ("brokenbetatwounc", b2u_wi, "broken beta2 unc, with sigma_int"),
        ("brokenlambdabreak", lb_wi,
         "break wavelength [um], with sigma_int"),
        ("brokenlambdabreakunc", lbu_wi,
         "break wavelength unc [um], with sigma_int"),
        ("brokenbetaonenosig", b1_no, "broken beta1, no sigma_int"),
        ("brokenbetaonenosigunc", b1u_no,
         "broken beta1 unc, no sigma_int"),
        ("brokenbetatwonosig", b2_no, "broken beta2, no sigma_int"),
        ("brokenbetatwonosigunc", b2u_no,
         "broken beta2 unc, no sigma_int"),
        ("brokenlambdabreaknosig", lb_no,
         "break wavelength [um], no sigma_int"),
        ("brokenlambdabreaknosigunc", lbu_no,
         "break wavelength unc [um], no sigma_int"),
        ("singlechired", chired(wi, "shared"),
         "single power law chi2_nu vs meas err, with sigma_int"),
        ("brokenchired", chired(wi, "broken"),
         "broken power law chi2_nu vs meas err, with sigma_int"),
        ("singlechirednosig", chired(no, "shared"),
         "single power law chi2_nu vs meas err, no sigma_int"),
        ("brokenchirednosig", chired(no, "broken"),
         "broken power law chi2_nu vs meas err, no sigma_int"),
        ("dbicsinglebroken", dbic_gap(wi),
         "dBIC(single) - dBIC(broken), with sigma_int"),
        ("dbicsinglebrokennosig", dbic_gap(no),
         "dBIC(single) - dBIC(broken), no sigma_int"),
    ]


def build_newcommand_block(cmds: List[Tuple[str, str, str]]) -> str:
    """Assemble the marker-delimited newcommand block as a string.

    Generated by Claude Opus 4.8 on 2026-07-14 (same layout as
    drivers/calc_fourstar_significant.py:build_block).

    Args:
        cmds: Ordered list of (name, value_str, comment) tuples.

    Returns:
        The block text (BEGIN marker, one \\newcommand per command with
        an aligned trailing comment, END marker), without a trailing
        newline.
    """
    width = max(len(name) + len(val) for name, val, _ in cmds)
    lines = [BLOCK_BEGIN]
    for name, val, comment in cmds:
        cmd = r"\newcommand{\%s}{%s}" % (name, val)
        pad = " " * (width - len(name) - len(val))
        lines.append(f"{cmd}{pad}  % {comment}")
    lines.append(BLOCK_END)
    return "\n".join(lines)


def write_ms_newcommands(
    ms_path: str, cmds: List[Tuple[str, str, str]], dry_run: bool = False,
) -> str:
    """Write the auto-generated newcommand block into ms.tex.

    Replaces the existing marker-delimited block if present; otherwise
    inserts it (first-run bootstrap) immediately after the
    calc_fourstar_significant.py block, or, failing that, just before
    ``\\begin{document}``. Replacements go through a function so
    backslashes in the block are inserted literally rather than
    interpreted as ``re`` replacement escapes.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        ms_path: Path to ms.tex.
        cmds: Ordered list of (name, value_str, comment) tuples.
        dry_run: If True, do not write; just return the block.

    Returns:
        The block text that was (or would be) written.
    """
    with open(ms_path) as f:
        text = f.read()
    block = build_newcommand_block(cmds)

    block_pat = re.compile(
        re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END), re.DOTALL
    )
    if block_pat.search(text):
        new_text, n = block_pat.subn(lambda _m: block, text)
    else:
        fourstar_end = "% END fourstar depth-ratio values"
        if fourstar_end in text:
            anchor = fourstar_end
            new_text = text.replace(anchor, anchor + "\n" + block, 1)
        elif r"\begin{document}" in text:
            anchor = r"\begin{document}"
            new_text = text.replace(anchor, block + "\n" + anchor, 1)
        else:
            raise ValueError(
                f"no beta-fit block, fourstar block, or "
                f"\\begin{{document}} anchor found in {ms_path}"
            )
        n = 1
    if n != 1:
        raise ValueError(
            f"expected exactly one beta-fit block in {ms_path}, "
            f"replaced {n}"
        )

    if not dry_run:
        with open(ms_path, "w") as f:
            f.write(new_text)
    return block


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Run the three beta fits and write all outputs.

    Generated by Claude Code on 2026-06-21.

    Args:
        argv: Optional argument vector (defaults to sys.argv).

    Returns:
        Process exit code.
    """
    p = argparse.ArgumentParser(description="dip-depth beta fits")
    p.add_argument("--defaults", action="store_true",
                   help="use default exclusions, no prompt")
    p.add_argument("--include-all", action="store_true",
                   help="no exclusions")
    p.add_argument("--exclude", type=str, default=None,
                   help='explicit exclusion set, e.g. "4,9,13"')
    p.add_argument("--refit", action="store_true",
                   help="ignore cache and resample")
    p.add_argument("--outdir", type=str, default=None,
                   help="override output directory")
    p.add_argument("--no-ms-newcommands", action="store_true",
                   help="skip writing the ms.tex newcommand block")
    args = p.parse_args(argv)

    outdir_base = args.outdir or join(RESULTSDIR, "beta_fit")

    df_all = fdb.load_depths(CSV_PATH)
    excluded = resolve_exclusions(df_all, args)

    # Run two variants: one that fits an intrinsic-scatter term and one
    # that does not (the latter lets chi^2 expose model misfit directly).
    # The no-sigma_int variant floors the depth error at 0.1% so a few
    # sub-0.1% literature errors do not dominate the fit.
    variants = [
        (True, 0.0, "with_sigma_int"),
        (False, 0.1, "no_sigma_int"),
    ]

    # Outer loop over the dataset axis (combined / thiswork / literature),
    # inner loop over the sigma-int variants. Exclusions are resolved once
    # on the combined table (above) and reused for every dataset; for the
    # literature dataset the TIC 262400835 exclusions are simply no-ops.
    for ds_name, ds_cats in DATASETS:
        df = fdb.load_depths(
            CSV_PATH, exclude_row_ids=excluded, categories=ds_cats
        )
        data = fdb.prepare_arrays(df, SVO_DIR)

        print(f"\n========== Dataset: {ds_name} ==========")
        print(f"Included measurements : {data['n']}")
        print(f"Epochs / stars        : {data['N_e']} / {data['N_s']}")
        print(f"Excluded row_ids      : {excluded}\n")

        # Collects each sigma_int variant's Table 7 ingredients for the
        # "combined" dataset only (Table 7, in beta_fit_summary.tex,
        # never draws on the thiswork-only/literature-only subsets);
        # export_fitresults_table runs once both variants are in hand.
        fitresults_ingredients = {}
        for fit_si, floor_pct, sub in variants:
            cfg = dict(fdb.DEFAULT_CFG)
            cfg["fit_sigma_int"] = fit_si
            cfg["depth_err_floor_pct"] = floor_pct
            vdata = fdb.apply_err_floor(data, floor_pct)
            outdir = join(outdir_base, ds_name, sub)
            idatas, bic_df = run_variant(
                vdata, cfg, outdir, excluded, variant_tag=sub,
                refit=args.refit, dataset=ds_name, categories=ds_cats,
            )
            if ds_name == "combined":
                fitresults_ingredients[sub] = (
                    fdb.collect_fitresults_ingredients(
                        idatas, vdata, bic_df
                    )
                )

        if ds_name == "combined":
            tex_path = join(outdir_base, "combined",
                             "tab_fitresults_rows.tex")
            fdb.export_fitresults_table(fitresults_ingredients, tex_path)
            LOG.info("Wrote Table 7 data rows to %s", tex_path)

            if not args.no_ms_newcommands:
                cmds = collect_ms_newcommands(fitresults_ingredients)
                block = write_ms_newcommands(MS_TEX, cmds)
                LOG.info("Wrote %d newcommands to %s", len(cmds), MS_TEX)
                for line in block.splitlines():
                    print(f"    {line}")

    return 0


def run_variant(
    data: dict, cfg: dict, outdir: str, excluded: Sequence[int],
    variant_tag: str, refit: bool = False, dataset: str = "combined",
    categories: Optional[Sequence[str]] = None,
) -> tuple:
    """Fit all three models for one sigma_int choice and write outputs.

    Plot filenames are suffixed with ``variant_tag`` (e.g.
    ``money_plot_beta_with_sigma_int.pdf``) even though it is already
    encoded in ``outdir``, so the two variants' PDFs can be told apart
    when copied side by side for comparison.

    Generated by Claude Code on 2026-06-21. Return value extended by
    Claude Sonnet 5 on 2026-07-04 to support Table 7 generation
    (fdb.collect_fitresults_ingredients/export_fitresults_table) without
    a second, cache-only re-fit pass.

    Args:
        data: Output of prepare_arrays.
        cfg: Sampler/model config (its ``fit_sigma_int`` flag selects
            the variant).
        outdir: Output directory for this variant.
        excluded: Excluded row_ids (recorded in run_config.json).
        variant_tag: Short variant label appended to plot filenames
            (e.g. "with_sigma_int", "no_sigma_int").
        refit: If True, ignore the fit cache and resample.
        dataset: Dataset-axis name (e.g. "combined", "thiswork",
            "literature"); recorded in run_config.json and the SUMMARY line.
        categories: The category filter for this dataset (e.g.
            ["This work"], or None for combined); recorded in
            run_config.json. Not used by the sampler.

    Returns:
        Tuple (idatas, bic_df): idatas is model_name -> fit for
        "shared", "perstar", "broken", "perdip"; bic_df is the
        model-comparison table with the ``dBIC`` column added (same
        content as the written ``bic_comparison.csv``).
    """
    fit_si = cfg.get("fit_sigma_int", True)
    cache_dir = join(outdir, "cache")
    os.makedirs(cache_dir, exist_ok=True)

    tag = "WITH sigma_int" if fit_si else "NO sigma_int (sigma = s)"
    key = fdb._cache_key("shared", data, cfg)
    print(f"\n########## Variant: {tag} ##########")
    print(f"Output dir   : {outdir}")
    print(f"Cache key    : {key[:16]}")

    idatas = {}
    for name in ("shared", "perstar", "broken", "perdip"):
        LOG.info("[%s] fitting model: %s", tag, name)
        idatas[name] = fdb.get_or_fit(
            name, data, cfg, cache_dir, refit=refit
        )

    # Model comparison (Delta-BIC).
    rows = [fdb.compute_bic(name, idatas[name], data, cfg)
            for name in ("shared", "perstar", "broken", "perdip")]
    bic_df = pd.DataFrame(rows)
    bic_df["dBIC"] = bic_df["BIC"] - bic_df["BIC"].min()
    bic_df.to_csv(join(outdir, "bic_comparison.csv"), index=False)

    print("\n=== Model comparison (Delta-BIC) ===")
    cols = ["model", "k", "dof", "sigma_int", "chi2red_meas_err",
            "chi2red_incl_sigma_int", "BIC", "dBIC"]
    print(bic_df[cols].to_string(
        index=False, float_format=lambda v: f"{v:.2f}"))
    if fit_si:
        print("chi2red_incl_sigma_int ~1 by construction; "
              "chi2red_meas_err shows residual misfit vs measurement "
              "error alone.")
    else:
        print("sigma_int not fitted: chi2red_meas_err == "
              "chi2red_incl_sigma_int is the true goodness of fit.")
    print("Reading: dBIC > 10 => strong preference for the lower-BIC "
          "model.\n")

    # PSIS-LOO / WAIC comparison.  Reuses the idatas already in memory
    # (a pure re-analysis of the cached posterior draws -- no refitting):
    # PSIS-LOO's effective parameter count p_loo and per-point Pareto k
    # diagnose how much of Model 4 (perdip)'s raw-k flexibility actually
    # earns its keep, and flag the mechanically-saturated two-band dips.
    loo_rows = [fdb.compute_loo(name, idatas[name])
                for name in ("shared", "perstar", "broken", "perdip")]
    loo_df = pd.DataFrame(loo_rows)
    loo_df.to_csv(join(outdir, "loo_comparison.csv"), index=False)

    compare_df = fdb.compare_models(idatas)
    compare_df.to_csv(join(outdir, "loo_compare.csv"), index=False)

    pointwise = pd.concat(
        [fdb.export_loo_pointwise_df(name, idatas[name], data)
         for name in ("shared", "perstar", "broken", "perdip")],
        ignore_index=True,
    )
    pointwise.to_csv(
        join(outdir, f"loo_pointwise_{variant_tag}.csv"), index=False
    )

    print("\n=== Model comparison (PSIS-LOO; higher elpd = better) ===")
    loo_cols = ["model", "elpd_loo", "se_loo", "p_loo", "elpd_waic",
                "p_waic", "n_khat_high", "n_khat_medium", "warning_loo"]
    print(loo_df[loo_cols].to_string(
        index=False, float_format=lambda v: f"{v:.2f}"))
    print("\n=== az.compare (paired elpd_diff with propagated dse) ===")
    print(compare_df.to_string(
        index=False, float_format=lambda v: f"{v:.2f}"))

    # The actual deliverable: for perdip, p_loo vs raw k, and how many
    # high-Pareto-k points fall in mechanically-saturated 2-band dips.
    k_perdip = int(bic_df.loc[bic_df["model"] == "perdip", "k"].iloc[0])
    p_loo_perdip = float(
        loo_df.loc[loo_df["model"] == "perdip", "p_loo"].iloc[0])
    pw_pd = pointwise[pointwise["model"] == "perdip"]
    high = pw_pd[pw_pd["pareto_k"] > 0.7]
    n_high, n_tot = len(high), len(pw_pd)
    n_high_2band = int((high["n_bands_in_dip"] == 2).sum())
    frac_pts = n_high / n_tot if n_tot else float("nan")
    frac_2band = n_high_2band / n_high if n_high else float("nan")
    print(f"\n[perdip] p_loo = {p_loo_perdip:.1f} vs raw k = {k_perdip} "
          f"(so ~{k_perdip - p_loo_perdip:.1f} of the {k_perdip} raw "
          "parameters are not earning their keep out-of-sample).")
    print(f"[perdip] Pareto k > 0.7 (unreliable/overly influential): "
          f"{n_high}/{n_tot} points ({100 * frac_pts:.0f}%); of those, "
          f"{n_high_2band} ({100 * frac_2band:.0f}%) are in 2-band dips.")
    print("PSIS-LOO Pareto-k warnings above are the diagnostic signal, "
          "not noise.\n")

    # Figures.  Filenames carry the variant_tag suffix so the two
    # variants' PDFs remain distinguishable when gathered together.
    vt = variant_tag
    fdb.plot_money(
        idatas, data, join(outdir, f"money_plot_beta_{vt}.pdf"),
        fit_sigma_int=fit_si,
    )
    # Same figure, linear-linear axes (y in [0,3], same x range): a
    # visualization check on how the relation reads without the log-log
    # compression.
    fdb.plot_money(
        idatas, data, join(outdir, f"money_plot_beta_{vt}_linear.pdf"),
        fit_sigma_int=fit_si, log_axes=False,
    )
    for name in ("shared", "perstar", "broken", "perdip"):
        fdb.plot_qa(
            name, idatas[name], join(outdir, f"qa_{name}_{vt}.pdf")
        )
    fdb.plot_beta_violins(
        idatas["shared"], idatas["perstar"], data,
        join(outdir, f"beta_violins_{vt}.pdf"),
    )
    fdb.plot_depth_scatter(
        idatas["shared"], idatas["perstar"], idatas["broken"], data,
        join(outdir, f"depth_scatter_{vt}.pdf"),
    )
    fdb.export_perdip_table(
        idatas["perdip"], data, join(outdir, f"perdip_beta_{vt}.csv")
    )
    fdb.export_samebandpair_table(
        idatas["perdip"], data,
        join(outdir, f"perdip_samebandpair_{vt}.csv"),
    )
    fdb.plot_beta_dip_violins(
        idatas["perstar"], idatas["perdip"], data,
        join(outdir, f"beta_dip_violins_{vt}.pdf"),
    )

    best = bic_df.loc[bic_df["BIC"].idxmin(), "model"]
