# Sentinel comments delimiting the auto-generated newcommand block in
# ms.tex, mirroring drivers/calc_fourstar_significant.py.  The whole
# span between them is rewritten each run, so the set of commands stays
# in sync with the "combined" beta fit and edits are idempotent.
# Unadorned command names are the fiducial with-sigma_int variant; the
# "nosig" suffix denotes the no-sigma_int variant.  These commands feed
