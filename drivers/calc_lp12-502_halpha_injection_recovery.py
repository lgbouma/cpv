def ew_mA_from_peak(h, sigma_v_kms):
    """Emission EW [mA] of a Gaussian of peak height h (continuum units).

    EW = integral of (flux/continuum - 1) dlambda; for a Gaussian of peak h and
    velocity width sigma_v, EW_v = h sigma_v sqrt(2 pi) [km/s], converted to
    wavelength via lambda0/c.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        h: Gaussian peak height in continuum-normalized units.
        sigma_v_kms: Gaussian velocity width [km/s].

    Returns:
        Equivalent width in milli-Angstrom.
    """
    return h * sigma_v_kms * SQRT2PI * KMS_PER_ANGSTROM_INV * 1e3


def peak_from_ew_mA(ew_mA, sigma_v_kms):
    """Inverse of ``ew_mA_from_peak``: peak height for a target EW [mA].

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        ew_mA: Target equivalent width [milli-Angstrom].
        sigma_v_kms: Gaussian velocity width [km/s].

    Returns:
        Gaussian peak height in continuum-normalized units.
    """
    return ew_mA / (sigma_v_kms * SQRT2PI * KMS_PER_ANGSTROM_INV * 1e3)


def robust_flatten(v, f, deg=3, n_iter=3, clip=3.0):
    """Divide out a robust low-order polynomial continuum.

    The reduced HIRES spectra still carry the echelle blaze, so each spectrum is
    normalized by a sigma-clipped degree-``deg`` polynomial fit to the line-free
    continuum window (CONT_LO < |dv/veq| < CONT_HI).  Sigma clipping keeps line
    wings and cosmic rays from biasing the continuum high.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        v: Velocity array [km/s].
        f: Flux array (arbitrary normalization).
        deg: Polynomial degree.
        n_iter: Number of sigma-clip iterations.
        clip: Clip threshold in units of the residual std.

    Returns:
        Continuum-flattened flux (continuum ~ 1).
    """
    dv = v / VEQ
    good = (np.abs(dv) > CONT_LO) & (np.abs(dv) < CONT_HI) & np.isfinite(f)
    idx = np.where(good)[0]
    for _ in range(n_iter):
        c = np.polyfit(v[idx], f[idx], deg)
        resid = f[idx] - np.polyval(c, v[idx])
        s = np.std(resid)
        keep = np.abs(resid) < clip * s
        if keep.all():
            break
        idx = idx[keep]
    c = np.polyfit(v[idx], f[idx], deg)
    return f / np.polyval(c, v)


def _mad_sigma(x):
    """Robust standard deviation (1.4826 x MAD) of finite entries.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        x: Array.

    Returns:
        Robust sigma (float).
    """
    x = x[np.isfinite(x)]
    return 1.4826 * np.median(np.abs(x - np.median(x)))


def load_night(datestr):
    """Load, flatten, and mean-subtract one night's HIRES Halpha spectra.

    Reads the reduced HIRES spectra over a wide window, drops flare-contaminated
    exposures (per ``MAX_ELAPSED_HR``), flattens each by a robust continuum,
    subtracts the per-night mean profile (removing the static line), and builds
    the matched-filter mask: the clean circumstellar band DV_MIN < |dv/veq| <
    DV_MAX, minus sharp cosmic-ray/bad-pixel outliers (flagged at CR_NSIG sigma
    and grown by CR_GROW pixels).  The frozen mask is identical for the null and
    for injections, so injected signal never changes it.  Smooth few-percent
    continuum systematics are deliberately KEPT: they are the real noise floor.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        datestr: HIRES run label, e.g. 'j546'.

    Returns:
        Dict with keys: v (n_spec, npix) velocity [km/s], dv (n_spec, npix)
        v/v_eq, resid (n_spec, npix) mean-subtracted flattened flux, weight
        (n_spec, npix) matched-filter mask, sigma (n_spec,) per-spectrum residual
        noise, spectimes (n_spec,) [TJD], mean (npix,) mean flattened profile,
        ff (n_spec, npix) flattened flux, and n_spec.
    """
    out = get_specriver_data(
        TICID, 'Hα', dlambda=20, gaussian_filter_sigma=None,
        usespectype='reduced', datestr=datestr,
    )
    _, spectimes, xvals, yvals, _, _ = out
    v = np.asarray(xvals, dtype=float)
    yvals = np.asarray(yvals, dtype=float)
    spectimes = np.asarray(spectimes, dtype=float)

    # drop flare-contaminated exposures for this night.
    elapsed_hr = (spectimes - spectimes.min()) * 24.0
    max_hr = MAX_ELAPSED_HR.get(datestr)
    if max_hr is not None:
        keep = elapsed_hr <= max_hr
        v, yvals, spectimes = v[keep], yvals[keep], spectimes[keep]
    n_spec, npix = yvals.shape

    ff = np.array([robust_flatten(v[i], yvals[i]) for i in range(n_spec)])
    mean = np.nanmean(ff, axis=0)
    resid = ff - mean[None, :]
    dv = v / VEQ

    band = (np.abs(dv) > DV_MIN) & (np.abs(dv) < DV_MAX) & np.isfinite(resid)
    sigma = np.array([_mad_sigma(resid[i][band[i]]) for i in range(n_spec)])

    # Sharp cosmic-ray / bad-pixel rejection: flag > CR_NSIG sigma pixels and
    # grow the flag by CR_GROW neighbors (CR wings), then re-estimate sigma from
    # the de-spiked residuals.  A real clump is resolved over ~sigma_v/dv_pix ~
    # 3-4 pixels and sits well below CR_NSIG near the limit, so it is untouched.
    cr = np.abs(resid) > (CR_NSIG * sigma[:, None])
    for _ in range(CR_GROW):
        cr[:, 1:] |= cr[:, :-1].copy()
        cr[:, :-1] |= cr[:, 1:].copy()
    weight = (band & ~cr).astype(float)
    sigma = np.array([
        _mad_sigma(resid[i][weight[i] > 0]) if (weight[i] > 0).any()
        else np.nan for i in range(n_spec)
    ])

    return dict(v=v, dv=dv, resid=resid, weight=weight, sigma=sigma,
                spectimes=spectimes, mean=mean, ff=ff, n_spec=n_spec)


def clump_velocities(spectimes, phi, k_kms):
    """Predicted clump RV per spectrum for orbital phase ``phi``.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        spectimes: Observation times [TJD].
        phi: Orbital phase offset [rad].
        k_kms: Orbital semi-amplitude [km/s].

    Returns:
        Array of clump center velocities [km/s], one per spectrum.
    """
    return k_kms * np.sin(2 * np.pi * spectimes / PERIOD_DAY + phi)


def template(v, mu, sigma_v_kms):
    """Unit-height Gaussian matched-filter template.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        v: Velocity array [km/s], shape (n_spec, npix).
        mu: Template centers [km/s], shape (n_spec,).
        sigma_v_kms: Template width [km/s].

    Returns:
        Template array, shape (n_spec, npix).
    """
    return np.exp(-((v - mu[:, None]) ** 2) / (2 * sigma_v_kms ** 2))


def matched_filter_AB(resid, weight, sigma, g):
    """Matched-filter numerator A_i and Fisher information B_i per spectrum.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        resid: Residual flux (n_spec, npix).
        weight: Mask (n_spec, npix).
        sigma: Per-spectrum noise (n_spec,).
        g: Template (n_spec, npix).

    Returns:
        Tuple (A, B) each of shape (n_spec,); A = sum w r g / sigma^2,
        B = sum w g^2 / sigma^2.  SNR_i = A_i / sqrt(B_i), amplitude = A_i / B_i.
    """
    inv_var = 1.0 / sigma[:, None] ** 2
    A = np.nansum(weight * resid * g * inv_var, axis=1)
    B = np.nansum(weight * g * g * inv_var, axis=1)
    return A, B


def recover(nd, sigma_v_kms, k_kms, ew_grid_mA, n_phi, rng):
    """Detection-statistic arrays for injected clumps vs EW and orbital phase.

    For each random orbital phase phi and each injected EW, inject the clump into
    the real (flattened) spectra, re-subtract the mean, and evaluate the two
    matched-filter detection statistics at the *known* injected track.  Because A
    is linear in the injected peak height, the per-phase noise term (A0) and the
    per-EW signal slope (D) are computed once per phase and combined, so the full
    EW grid is swept cheaply.  The mean-subtraction self-subtraction of the clump
    (g - <g>_spec) is included, as in the real analysis.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        nd: Night dict from ``load_night``.
        sigma_v_kms: Clump width [km/s].
        k_kms: Orbital semi-amplitude [km/s].
        ew_grid_mA: Injected EW grid [milli-Angstrom].
        n_phi: Number of random orbital phases.
        rng: numpy Generator.

    Returns:
        Tuple (stat_a, stat_b) each shape (len(ew_grid_mA), n_phi): the
        per-spectrum (max_i A_i/sqrt(B_i)) and stitching (sum A_i / sqrt(sum B_i))
        matched-filter SNR for every injected EW and phase.  Threshold these
        outside to get recovery fractions.
    """
    v, resid0, weight, sigma = nd['v'], nd['resid'], nd['weight'], nd['sigma']
    spectimes = nd['spectimes']
    inv_var = 1.0 / sigma[:, None] ** 2
    peaks = peak_from_ew_mA(ew_grid_mA, sigma_v_kms)   # (n_ew,)

    stat_a = np.zeros((len(ew_grid_mA), n_phi))
    stat_b = np.zeros((len(ew_grid_mA), n_phi))
    phis = rng.uniform(0, 2 * np.pi, n_phi)

    for p, phi in enumerate(phis):
        mu = clump_velocities(spectimes, phi, k_kms)
        g = template(v, mu, sigma_v_kms)             # template == injected shape
        gbar = np.nanmean(g, axis=0)
        g_ms = g - gbar[None, :]                      # mean-subtracted signal
        A0 = np.nansum(weight * resid0 * g * inv_var, axis=1)
        D = np.nansum(weight * g_ms * g * inv_var, axis=1)
        B = np.nansum(weight * g * g * inv_var, axis=1)
        sqrtB = np.sqrt(B)
        sqrtsumB = np.sqrt(np.nansum(B))
        for j, h in enumerate(peaks):
            A = A0 + h * D
            snr_i = np.zeros_like(A)
            np.divide(A, sqrtB, out=snr_i, where=B > 0)
            stat_a[j, p] = np.nanmax(snr_i)
            stat_b[j, p] = np.nansum(A) / sqrtsumB
    return stat_a, stat_b


def recovery_fraction(stat, thr):
    """Recovery fraction per EW at a detection threshold.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        stat: Statistic array (n_ew, n_phi).
        thr: Detection threshold (sigma).

    Returns:
        Recovery fraction array (n_ew,).
    """
    return np.mean(stat >= thr, axis=1)


def analytic_limits(nd, sigma_v_kms, k_kms, n_phi, rng):
    """Closed-form Gaussian matched-filter EW limits (cross-check).

    Uses the noise-free expectation E[A_i] = h B_i, so E[SNR] = h sqrt(B).  The
    5 sigma peak height is h = 5 / sqrt(B_eff), with B_eff the (phase-median)
    per-spectrum best sqrt(B) for the per-spectrum statistic and the (phase-
    median) sqrt(sum B) for stitching.  This is the ~50% recovery level (noise
    scatters the statistic +/-1 sigma about its mean).

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        nd: Night dict.
        sigma_v_kms: Clump width [km/s].
        k_kms: Orbital semi-amplitude [km/s].
        n_phi: Number of random phases to marginalize over.
        rng: numpy Generator.

    Returns:
        Tuple (ew_a_mA, ew_b_mA): analytic 5 sigma EW limits [milli-Angstrom].
    """
    v, weight, sigma = nd['v'], nd['weight'], nd['sigma']
    spectimes = nd['spectimes']
    inv_var = 1.0 / sigma[:, None] ** 2
    best_sqrtB, joint_sqrtB = [], []
    for phi in rng.uniform(0, 2 * np.pi, n_phi):
        mu = clump_velocities(spectimes, phi, k_kms)
        g = template(v, mu, sigma_v_kms)
        B = np.nansum(weight * g * g * inv_var, axis=1)
        best_sqrtB.append(np.sqrt(np.nanmax(B)))
        joint_sqrtB.append(np.sqrt(np.nansum(B)))
    h_a = SNR_THRESH / np.median(best_sqrtB)
    h_b = SNR_THRESH / np.median(joint_sqrtB)
    return (ew_mA_from_peak(h_a, sigma_v_kms),
            ew_mA_from_peak(h_b, sigma_v_kms))


def blind_search(nd, sigma_v_kms, k_kms, n_phi_grid):
    """Blind phase/velocity search of the real (un-injected) residuals.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        nd: Night dict.
        sigma_v_kms: Template width [km/s].
        k_kms: Orbital semi-amplitude [km/s].
        n_phi_grid: Number of trial phases.

    Returns:
        Dict with the max per-spectrum statistic (over spectra and a velocity
        grid), the stitching statistic per trial phase (array) and its max, and
        the trial-phase grid.
    """
    v, resid, weight, sigma = nd['v'], nd['resid'], nd['weight'], nd['sigma']
    spectimes = nd['spectimes']
    phis = np.linspace(0, 2 * np.pi, n_phi_grid, endpoint=False)
    snr_b = np.zeros(n_phi_grid)
    for k, phi in enumerate(phis):
        mu = clump_velocities(spectimes, phi, k_kms)
        g = template(v, mu, sigma_v_kms)
        A, B = matched_filter_AB(resid, weight, sigma, g)
        snr_b[k] = np.nansum(A) / np.sqrt(np.nansum(B))

    # per-spectrum blind search: scan template center over the whole band.
    mu_grid = np.arange(-DV_MAX, DV_MAX + 1e-9, 0.25) * VEQ
    best_a = 0.0
    for mu0 in mu_grid:
        mu = np.full(nd['n_spec'], mu0)
        g = template(v, mu, sigma_v_kms)
        A, B = matched_filter_AB(resid, weight, sigma, g)
        snr_i = np.zeros_like(A)
        np.divide(A, np.sqrt(B), out=snr_i, where=B > 0)
        best_a = max(best_a, np.nanmax(snr_i))
    return dict(snr_b=snr_b, phis=phis, max_b=np.nanmax(snr_b), max_a=best_a)


def scramble_null_threshold(nd, sigma_v_kms, k_kms, n_phi_grid, n_scramble,
                            rng):
    """Systematics-aware stitching threshold from a time-scrambling null.

    The residuals contain non-periodic few-percent continuum systematics (smooth
    bumps in individual exposures) that a Gaussian-noise null would miss.  To
    calibrate the coherent (stitching) false-alarm level *including* those
    systematics, we repeatedly permute the exposure->time assignment (destroying
    any true sinusoidal phase coherence while preserving each exposure's residual
    structure), rerun the stitching phase search, and record the max statistic.
    A real periodic clump would not survive scrambling; systematic bumps still
    can occasionally line up on some trial sinusoid, so their contribution is
    folded into the threshold.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        nd: Night dict.
        sigma_v_kms: Template width [km/s].
        k_kms: Orbital semi-amplitude [km/s].
        n_phi_grid: Number of trial phases per scramble.
        n_scramble: Number of time permutations.
        rng: numpy Generator.

    Returns:
        Tuple (thr99, thr999): 99th and 99.9th percentiles of the scrambled max
        stitching statistic.
    """
    v, resid, weight, sigma = nd['v'], nd['resid'], nd['weight'], nd['sigma']
    spectimes, n_spec = nd['spectimes'], nd['n_spec']
    inv_var = 1.0 / sigma[:, None] ** 2
    phis = np.linspace(0, 2 * np.pi, n_phi_grid, endpoint=False)
    # Precompute per-(phase, exposure-slot) template sums.  Because scrambling
    # permutes which exposure occupies which time slot, we precompute, for each
    # trial phase and each *time slot*, the template a spectrum placed there
    # would use; then per scramble we gather the permuted rows.
    mus = np.array([clump_velocities(spectimes, p, k_kms) for p in phis])
    # per slot s and phase p: template row over pixels for a spectrum at mus[p,s]
    max_stat = np.zeros(n_scramble)
    # precompute, for each phase and slot, A-per-exposure and B-per-exposure as
    # functions of which real exposure fills that slot (matrix [phase, slot,
    # exposure] is large; instead loop scrambles, cheap enough).
    for m in range(n_scramble):
        perm = rng.permutation(n_spec)
        rp, wp, sp = resid[perm], weight[perm], (1.0 / sigma[perm] ** 2)
        best = -np.inf
        for p in range(n_phi_grid):
            g = template(v, mus[p], sigma_v_kms)   # slot s uses mus[p,s]
            A = np.nansum(wp * rp * g * sp[:, None], axis=1)
            B = np.nansum(wp * g * g * sp[:, None], axis=1)
            best = max(best, np.nansum(A) / np.sqrt(np.nansum(B)))
        max_stat[m] = best
    return np.percentile(max_stat, 99), np.percentile(max_stat, 99.9)


def crossing_ew(ew_grid, rec, target):
    """Smallest injected EW whose recovery fraction reaches ``target``.

    Log-linear interpolation on the first upward crossing of ``target``.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        ew_grid: Injected EW grid (ascending) [milli-Angstrom].
        rec: Recovery fraction at each grid point.
        target: Target recovery fraction (e.g. 0.95).

    Returns:
        Interpolated EW [milli-Angstrom], or np.nan if never reached.
    """
    rec = np.asarray(rec)
    above = rec >= target
    if not above.any():
        return np.nan
    # Saturated already at the smallest (~zero) injected EW: the statistic is
    # dominated by systematics / false alarms, so no meaningful limit exists.
    if rec[0] >= target:
        return np.nan
    j = np.argmax(above)          # first index at/above target
    if j == 0:
        return float(ew_grid[0])
    x0, x1 = np.log(ew_grid[j - 1]), np.log(ew_grid[j])
    y0, y1 = rec[j - 1], rec[j]
    if y1 == y0:
        return float(ew_grid[j])
    xt = x0 + (target - y0) * (x1 - x0) / (y1 - y0)
    return float(np.exp(xt))


