def main():
    """Run the injection-recovery exercise for all three nights.

    Generated by Claude Opus 4.8 on 2026-07-14.
    """
    os.makedirs(OUTDIR, exist_ok=True)
    rng = np.random.default_rng(RNG_SEED)
    k_kms = K_VEQ * VEQ
    sigv_fid = SIGMA_V_VEQ_FID * VEQ

    print('Loading nights...')
    nights = {n: load_night(n) for n in NIGHTS}
    for n, nd in nights.items():
        print(f'  {n}: n_spec={nd["n_spec"]}, median sigma_pix='
              f'{np.median(nd["sigma"]):.4f}, '
              f'span={np.ptp(nd["spectimes"])*24:.2f} hr')

    summary_rows, null_rows, nights_data = [], [], {}
    for night, nd in nights.items():
        print(f'\n=== {night} : injection-recovery (fiducial width) ===')
        stat_a, stat_b = recover(nd, sigv_fid, k_kms, EW_GRID_MA, N_PHI, rng)
        ana_a, ana_b = analytic_limits(nd, sigv_fid, k_kms, 400, rng)
        blind = blind_search(nd, sigv_fid, k_kms, N_PHI_GRID_BLIND)
        tau_b_emp, tau_b_999 = scramble_null_threshold(
            nd, sigv_fid, k_kms, N_PHI_GRID_SCRAMBLE, N_SCRAMBLE, rng)
        # per-spectrum systematics floor: the worst single-exposure bump the real
        # data already shows -- a single-exposure clump must beat it to count.
        tau_a_emp = max(SNR_THRESH, blind['max_a'])

        # recovery fractions and EW95 at the nominal (5 sigma) and empirical
        # (systematics-aware) detection thresholds.
        rec_a5 = recovery_fraction(stat_a, SNR_THRESH)
        rec_b5 = recovery_fraction(stat_b, SNR_THRESH)
        rec_a_emp = recovery_fraction(stat_a, tau_a_emp)
        rec_b_emp = recovery_fraction(stat_b, tau_b_emp)

        ew = dict(
            a5_50=crossing_ew(EW_GRID_MA, rec_a5, 0.50),
            a5_95=crossing_ew(EW_GRID_MA, rec_a5, 0.95),
            b5_50=crossing_ew(EW_GRID_MA, rec_b5, 0.50),
            b5_95=crossing_ew(EW_GRID_MA, rec_b5, 0.95),
            a_emp_95=crossing_ew(EW_GRID_MA, rec_a_emp, 0.95),
            b_emp_50=crossing_ew(EW_GRID_MA, rec_b_emp, 0.50),
            b_emp_95=crossing_ew(EW_GRID_MA, rec_b_emp, 0.95),
        )
        print(f'  per-spectrum : EW95(5sig)={ew["a5_95"]:.1f}  '
              f'EW95(emp {tau_a_emp:.1f}sig)={ew["a_emp_95"]:.1f}  '
              f'(analytic5sig {ana_a:.1f}) mA')
        print(f'  stitching    : EW95(5sig)={ew["b5_95"]:.1f}  '
              f'EW95(emp {tau_b_emp:.1f}sig)={ew["b_emp_95"]:.1f}  '
              f'(analytic5sig {ana_b:.1f}) mA')
        floor_a5, floor_b5 = float(rec_a5[0]), float(rec_b5[0])
        print(f'  false-alarm floor (recovery at EW~0): per-spec(5sig) '
              f'{floor_a5:.2f}, stitch(5sig) {floor_b5:.2f}')
        print(f'  blind real-data max: per-spec {blind["max_a"]:.1f}sig, '
              f'stitch {blind["max_b"]:.1f}sig | scramble thr(99/99.9%): '
              f'{tau_b_emp:.1f}/{tau_b_999:.1f}sig')

        nights_data[night] = dict(
            ew_grid=EW_GRID_MA, rec_a5=rec_a5, rec_b5=rec_b5,
            rec_b_emp=rec_b_emp, blind=blind, tau_b_emp=tau_b_emp,
            ew95_a5=ew['a5_95'], ew95_b5=ew['b5_95'], ew95_b_emp=ew['b_emp_95'])

        summary_rows += [
            dict(night=night, method='per_spectrum', threshold_kind='nominal',
                 threshold_sigma=SNR_THRESH, EW50_mA=ew['a5_50'],
                 EW95_mA=ew['a5_95'], EW_analytic_5sig_mA=ana_a,
                 n_spec=nd['n_spec'],
                 median_sigma_pix=float(np.median(nd['sigma'])),
                 real_blind_max_sigma=blind['max_a']),
            dict(night=night, method='per_spectrum', threshold_kind='empirical',
                 threshold_sigma=tau_a_emp, EW50_mA=np.nan,
                 EW95_mA=ew['a_emp_95'], EW_analytic_5sig_mA=ana_a,
                 n_spec=nd['n_spec'],
                 median_sigma_pix=float(np.median(nd['sigma'])),
                 real_blind_max_sigma=blind['max_a']),
            dict(night=night, method='stitching', threshold_kind='nominal',
                 threshold_sigma=SNR_THRESH, EW50_mA=ew['b5_50'],
                 EW95_mA=ew['b5_95'], EW_analytic_5sig_mA=ana_b,
                 n_spec=nd['n_spec'],
                 median_sigma_pix=float(np.median(nd['sigma'])),
                 real_blind_max_sigma=blind['max_b']),
            dict(night=night, method='stitching', threshold_kind='empirical',
                 threshold_sigma=tau_b_emp, EW50_mA=ew['b_emp_50'],
                 EW95_mA=ew['b_emp_95'], EW_analytic_5sig_mA=ana_b,
                 n_spec=nd['n_spec'],
                 median_sigma_pix=float(np.median(nd['sigma'])),
                 real_blind_max_sigma=blind['max_b']),
        ]
        null_rows.append(dict(
            night=night, real_max_per_spectrum_sig=blind['max_a'],
            real_max_stitching_sig=blind['max_b'],
            scramble_thr99_stitching_sig=tau_b_emp,
            scramble_thr999_stitching_sig=tau_b_999,
            per_spectrum_floor_sig=tau_a_emp,
            false_alarm_frac_perspec_5sig=floor_a5,
            false_alarm_frac_stitch_5sig=floor_b5,
            nominal_threshold_sig=SNR_THRESH))

    summary_df = pd.DataFrame(summary_rows)
    summary_df.to_csv(join(OUTDIR, 'injrec_summary.csv'), index=False)
    null_df = pd.DataFrame(null_rows)
    null_df.to_csv(join(OUTDIR, 'null_and_thresholds.csv'), index=False)
    print(f'\nMade {join(OUTDIR, "injrec_summary.csv")}')
    print(f'Made {join(OUTDIR, "null_and_thresholds.csv")}')

    # --- width sensitivity (EW95 vs sigma_v) ---
    # Stitching is quoted at the nominal 5 sigma (its false-alarm floor is small);
    # per-spectrum is quoted at its empirical systematics floor (the blind
    # single-exposure max for that width), because per-spectrum at 5 sigma is
    # saturated by continuum systematics and gives no meaningful limit.
    print('\n=== width sensitivity ===')
    width_rows = []
    for night, nd in nights.items():
        for wv in WIDTH_GRID_VEQ:
            sa, sb = recover(nd, wv * VEQ, k_kms, EW_GRID_MA, N_PHI, rng)
            tau_a = max(SNR_THRESH,
                        blind_search(nd, wv * VEQ, k_kms,
                                     N_PHI_GRID_BLIND)['max_a'])
            width_rows.append(dict(
                night=night, sigma_v_veq=wv,
                EW95_per_spectrum_empirical_mA=crossing_ew(
                    EW_GRID_MA, recovery_fraction(sa, tau_a), 0.95),
                EW95_stitching_5sig_mA=crossing_ew(
                    EW_GRID_MA, recovery_fraction(sb, SNR_THRESH), 0.95)))
    width_df = pd.DataFrame(width_rows)
    width_df.to_csv(join(OUTDIR, 'width_sensitivity.csv'), index=False)
    print(f'Made {join(OUTDIR, "width_sensitivity.csv")}')

    # --- plots ---
    plot_recovery_curves(nights_data, join(OUTDIR, 'recovery_curves.png'))
    plot_blind_search(nights_data, join(OUTDIR, 'blind_search.png'))
    for night, nd in nights.items():
        ew_demo = nights_data[night]['ew95_b_emp']
        if not np.isfinite(ew_demo):
            ew_demo = nights_data[night]['ew95_b5']
        if not np.isfinite(ew_demo):
            ew_demo = 20.0
        plot_residual_river(
            nd, night, ew_demo, sigv_fid, k_kms,
            join(OUTDIR, f'residual_river_{night}.png'), rng)

    # --- human-readable summary ---
    write_results_txt(summary_df, null_df, width_df, nights)
    print('\nDone.')


