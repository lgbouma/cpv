"""
Injection-recovery for sinusoidal-in-time Halpha clump emission on LP 12-502
(TIC 402980664), using the Keck/HIRES spectra of nights j531, j546, and j547.

Motivation
----------
In some CPV datasets (e.g. TIC 141146667; see
`hotcold/drivers/halpha_to_rv_timeseries.py`) the Halpha profile shows extra
emission whose radial velocity varies *sinusoidally in time*, as expected from a
plasma clump on a (nearly) circular circumstellar orbit corotating with the
star.  LP 12-502 does NOT show such a feature.  This driver quantifies that
non-detection: down to what emitting equivalent width (EW) do these HIRES
spectra rule out a sinusoidally-moving Halpha emission clump?

Model
-----
A clump on a circular orbit of period P (= the known 18.56 hr rotation period)
produces a Gaussian emission line whose center follows

    v(t) = K sin(2 pi t / P + phi),

with K the projected orbital velocity.  The question is only well posed for
*circumstellar* velocities (v/v_eq ~ 2-8, i.e. r/R_star ~ 2-8 for corotation);
we adopt K = 4 v_eq as a fiducial (v_eq = 24.2 km/s so K = 96.8 km/s).  The
clump line width is a nuisance parameter; we adopt sigma_v = 0.2 v_eq as the
fiducial (matching the widths fit in the reference driver) and report a small
sensitivity grid.

Method
------
The static Halpha line and the continuum are removed by subtracting the
per-night mean spectrum; a *moving* clump does not cancel.  On the residual
spectra we run a matched filter (a Gaussian template of width sigma_v at the
predicted velocity) and form two detection statistics:

  (a) per-spectrum:  S_a = max_i A_i / sqrt(B_i)
        -- the most significant single-exposure clump anywhere along the orbit;
  (b) stitching:     S_b = (sum_i A_i) / sqrt(sum_i B_i)
        -- coherent coaddition of the matched filter along the sinusoidal RV
           track (uses the known ephemeris), deeper by ~sqrt(N_spec).

Here A_i = sum_p w_p r_{i,p} g_{i,p}/sigma_i^2 and B_i = sum_p w_p g_{i,p}^2 /
sigma_i^2 are the standard matched-filter numerator (amplitude x information)
and Fisher information for spectrum i; g is the unit-height Gaussian template,
w_p a mask (line core and off-band pixels and cosmic rays excluded), and sigma_i
the per-spectrum residual noise.  Under the null (no clump, Gaussian noise) each
local A_i/sqrt(B_i) ~ N(0,1), so these statistics are in units of sigma; we
require 5 sigma to claim a detection.

The limiting EW is defined by injection-recovery *into the real spectra*: for a
grid of injected EWs and many random orbital phases phi, inject the clump, run
the detector, and record the fraction of phases recovered at >=5 sigma.  The
limiting EW is the value recovered for >=95% of phases (we also report the 50%
value).  Because the real data are used as the noise realization, EW=0 recovery
measures the actual false-alarm rate (and doubles as the null test: a blind
phase search of the un-injected data stays below 5 sigma).  A closed-form
Gaussian matched-filter limit is reported alongside as a cross-check.

Outputs (results/LP12502_Halpha_injection_recovery/)
  - injrec_summary.csv       : EW50/EW95 (per-spectrum & stitching) + analytic,
                               per night, fiducial width.
  - width_sensitivity.csv    : EW95 vs sigma_v for a small width grid.
  - null_and_thresholds.csv  : blind-search max statistic on the real (un-
                               injected) data, and the empirical 99th-percentile
                               false-alarm threshold from a Gaussian-noise MC.
  - recovery_curves.png      : recovery fraction vs injected EW, both methods,
                               per night, with the 50/95% limits marked.
  - residual_river_<night>.png : trailed residual spectra with an injected clump
                               at the stitching limit overplotted (visual proof).
  - blind_search.png         : stitching-search SNR vs trial phase on the real
                               data (shows no significant peak).
  - RESULTS.txt              : human-readable summary and interpretation.

Usage:
    conda run -n cpv python drivers/calc_lp12-502_halpha_injection_recovery.py

Generated by Claude Opus 4.8 on 2026-07-14.
"""
