def plot_residual_river(nd, night, ew_inject_mA, sigma_v_kms, k_kms, path,
                        rng):
    """Trailed residual spectra with an injected clump at the stitching limit.

    Generated by Claude Opus 4.8 on 2026-07-14.

    Args:
        nd: Night dict.
        night: Night label.
        ew_inject_mA: EW of the injected demonstration clump [milli-Angstrom].
        sigma_v_kms: Clump width [km/s].
        k_kms: Orbital semi-amplitude [km/s].
        path: Output PNG path.
        rng: numpy Generator (for the demo phase).
    """
    set_style('science')
    v, dv, resid, spectimes = nd['v'], nd['dv'], nd['resid'], nd['spectimes']
    n_spec = nd['n_spec']
    order = np.argsort(spectimes)
    phi = rng.uniform(0, 2 * np.pi)
    mu = clump_velocities(spectimes, phi, k_kms)
    h = peak_from_ew_mA(ew_inject_mA, sigma_v_kms)
    g = template(v, mu, sigma_v_kms)
    inj = resid + h * (g - np.nanmean(g, axis=0)[None, :])

    dvgrid = dv[0]
    extent = [dvgrid.min(), dvgrid.max(), 0, n_spec]
    band = nd['weight'] > 0
    vlim = np.nanpercentile(np.abs(resid[band]), 97) if band.any() else 0.05
    # blank everything outside the clean search band so the eye focuses on the
    # clump region; the masked (line + off-band) pixels render as light grey.
    outside = ~((np.abs(dvgrid) > DV_MIN) & (np.abs(dvgrid) < DV_MAX))
    cmap = plt.get_cmap('RdBu_r').copy()
    cmap.set_bad('0.82')
    fig, axs = plt.subplots(1, 2, figsize=(8, 5), sharey=True)
    for ax, data, ttl in [
            (axs[0], resid, 'real residuals'),
            (axs[1], inj,
             f'+ injected clump ({ew_inject_mA:.0f} m$\\mathrm{{\\AA}}$)')]:
        show = data[order].copy()
        show[:, outside] = np.nan
        ax.imshow(show, aspect='auto', origin='lower', extent=extent,
                  cmap=cmap, vmin=-vlim, vmax=vlim, interpolation='nearest')
        yy = np.arange(n_spec) + 0.5
        ax.plot(mu[order] / VEQ, yy, color='k', lw=1.0, alpha=0.7, ls='--')
        ax.set_xlabel(r'$\Delta v / v_\mathrm{eq}$')
        ax.set_title(ttl, fontsize='medium')
        ax.set_xlim(-DV_MAX - 0.8, DV_MAX + 0.8)
    axs[0].set_ylabel('spectrum (time-ordered) $\\rightarrow$')
    fig.suptitle(f'LP 12-502  {night}: residual trailed spectra '
                 f'(injected clump K={k_kms/VEQ:.0f}$v_{{eq}}$, '
                 f'$\\sigma_v$={sigma_v_kms/VEQ:.1f}$v_{{eq}}$; '
                 f'grey = excluded line region)', fontsize='small')
    fig.tight_layout()
    fig.savefig(path, dpi=200)
    plt.close(fig)
    print(f'Made {path}')


