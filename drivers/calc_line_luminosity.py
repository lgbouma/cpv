"""Convert an emission-line EW to a line luminosity via the chi method.

L_line = chi(lambda, Teff) * EW * L_bol, where
chi = pi * B_lambda(Teff) / (sigma * Teff^4) is the blackbody
continuum-to-bolometric flux ratio (per Angstrom).

The blackbody chi is an upper bound for mid-late M types, where TiO
suppresses the true 6563 AA continuum by ~2x.  For calibrated values
see Douglas et al. 2014 (ADS: 2014ApJ...795..161D) and Newton et al.
2017 (ADS: 2017ApJ...834...85N).

Generated by Claude Fable 5 on July 7 2026.
"""
import numpy as np
import astropy.constants as const
import astropy.units as u


def chi_blackbody(lam: u.Quantity, teff: u.Quantity) -> u.Quantity:
    """Blackbody continuum-to-bolometric flux ratio, per Angstrom.

    Generated by Claude Fable 5 on July 7 2026.

    Args:
        lam: Wavelength of the line (e.g., 6562.8 * u.AA).
        teff: Effective temperature (e.g., 3159 * u.K).

    Returns:
        chi = pi * B_lambda / (sigma_sb * Teff^4), in 1/AA.
    """
    x = (const.h * const.c / (lam * const.k_B * teff)).decompose()
    b_lam = (2 * const.h * const.c**2 / lam**5) / np.expm1(x)
    f_lam = np.pi * b_lam  # surface flux density
    f_bol = const.sigma_sb * teff**4
    return (f_lam / f_bol).to(1 / u.AA)


def line_luminosity(
    ew: u.Quantity,
    lbol: u.Quantity,
    teff: u.Quantity,
    lam: u.Quantity = 6562.8 * u.AA,
    log10_chi: float | None = None,
) -> u.Quantity:
    """Line luminosity from EW, L_bol, and a continuum chi factor.

    Generated by Claude Fable 5 on July 7 2026.

    Args:
        ew: Emission equivalent width (positive; e.g., 6 * u.AA).
        lbol: Bolometric luminosity (e.g., 0.033 * u.Lsun).
        teff: Effective temperature; used for the blackbody chi.
        lam: Line wavelength.  Default is H-alpha.
        log10_chi: If given, use 10**log10_chi (1/AA) instead of the
            blackbody chi (e.g., a Douglas et al. 2014 value).

    Returns:
        Line luminosity, in erg/s.
    """
    if log10_chi is None:
        chi = chi_blackbody(lam, teff)
    else:
        chi = 10**log10_chi / u.AA
    return (chi * ew * lbol).to(u.erg / u.s)


CASES = {
    "300651846": {
        "ew": 6.0 * u.AA,
        "teff": 3159 * u.K,
        "lbol": 0.033 * u.Lsun,
    },
    "402980664": {
        "ew": 0.22 * u.AA,
        "teff": 3090 * u.K,
        "lbol": 0.0112 * u.Lsun,
    },
}


def main(ticid: str = "402980664") -> None:
    """Run the chi-method calculation for a given TIC ID.

    Generated by Claude Fable 5 on July 7 2026.

    Args:
        ticid: Key into CASES ("300651846" or "402980664").
    """
    case = CASES[ticid]
    ew = case["ew"]
    teff = case["teff"]
    lbol = case["lbol"]
    lam = 6562.8 * u.AA

    print(f"TIC {ticid}")

    chi = chi_blackbody(lam, teff)
    lline = line_luminosity(ew, lbol, teff, lam)
    ratio = (lline / lbol).decompose()

    print(f"Teff = {teff:.0f}, Lbol = {lbol:.3f}, EW = {ew:.1f}")
    print(f"chi_BB          = {chi:.3e}")
    print(f"L_line (BB)     = {lline:.3e}")
    print(f"log L_line/Lbol = {np.log10(ratio.value):.2f}")

    print("\nPHOENIX-scale chi (Douglas+14, ~M3-M4):")
    for log10_chi in [-4.4, -4.5, -4.6]:
        ll = line_luminosity(ew, lbol, teff, lam, log10_chi=log10_chi)
        lr = np.log10((ll / lbol).decompose().value)
        print(f"  log chi = {log10_chi:5.2f}: "
              f"L_line = {ll:.2e}, log L/Lbol = {lr:.2f}")


if __name__ == "__main__":
    import sys
    main(sys.argv[1] if len(sys.argv) > 1 else "402980664")
