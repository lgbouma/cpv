"""Allowed core-halo parameters given the fitted broken-PL slopes.

The core-halo model (Eq. eq:corehalo of the ms) in units of A_c is
    delta(lam) = 1 + R * [1 - exp(-tau_h(lam))],
    tau_h(lam) = tau0 * (lam / LAM_REF)^-beta,      R = A_h / A_c.
Its effective slopes are compared against the fiducial broken-PL fit
(beta1 blueward of the break, beta2 redward), read from ms.tex so the
targets cannot drift from the manuscript.

A brute-force grid over (beta, tau0, R) maps chi2(beta1, beta2) and
the result is shown corner-style: 1-d panels give the profile
Delta-chi2 for each parameter (minimized over the other two), 2-d
panels give joint Delta-chi2 = 2.30 / 6.18 contours (68 / 95% for two
parameters).  Frequentist profiling is used instead of marginalizing
because the three parameters are constrained by only two numbers, so
the answer is a degenerate ridge; profiling reports its extent
without a prior-volume dependence.

Effective slopes are two-point log-log slopes across 0.4--1.0 um
(blue) and 1.4--2.2 um (red), matching the windows quoted in the ms
subsection draft.

Output: results/allowed_core_halo_params/allowed_core_halo_params.png
(+ printed 68 / 95% profile intervals and the best-fit point).

Usage:
    python drivers/calc_allowed_core_halo_params.py
"""
import os
import re
from os.path import dirname, join
from typing import Dict, Tuple

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.colors import LogNorm

from aesthetic.plot import set_style

try:
    from complexrotators.paths import RESULTSDIR
except ImportError:
    RESULTSDIR = join(dirname(__file__), "..", "results")

OUTDIR = join(RESULTSDIR, "allowed_core_halo_params")
MS_TEX = join(dirname(__file__), "..", "papers", "Bouma_2026_cgcd",
              "ms.tex")

LAM_REF = 1.2      # tau0 reference wavelength [micron]
LAM_BLUE = (0.4, 1.0)   # blue slope window [micron]
LAM_RED = (1.4, 2.2)    # red slope window [micron]

# Fallbacks if ms.tex is not found (fiducial with-sigma_int values).
FALLBACK_TARGETS = {"beta1": 0.79, "beta1_unc": 0.16,
                    "beta2": -0.09, "beta2_unc": 0.39}

# Grid: beta linear; tau0 and R logarithmic.
N_GRID = 160
BETA_GRID = np.linspace(0.2, 10.0, N_GRID)
TAU0_GRID = np.geomspace(1e-5, 1e1, N_GRID)
R_GRID = np.geomspace(1e-2, 1e4, N_GRID)

# Physical priors, overlaid on the plot rather than baked into chi2.
# (i) Compact grains cannot exceed the Rayleigh-scattering slope
#     (kappa ~ lam^-4); ISM-like sub-micron populations give beta~2.
BETA_ISM = 2.0
BETA_MAX = 4.0
# (ii) Core + halo must fit on the stellar disk.  With an opaque
#     core, delta_IR ~ A_c/A_star, so A_h/A_c <= 1/delta_IR - 1.
#     Lines are drawn for representative gray-floor depths.
DELTA_IR = (0.01, 0.03)

# Representative model; matches the core+halo toy plotted in
# plot_diluted_transmission_spectrum.py (Delta-chi2 = 0.7 vs the
# global minimum, inside the joint 68% region).
REP = {"beta": 2.0, "tau0": 0.09, "R": 3.0}

# Delta-chi2 thresholds: (1-param 68, 95), (2-param joint 68, 95).
DCHI2_1D = (1.0, 4.0)
DCHI2_2D = (2.30, 6.18)


def parse_targets(ms_tex: str = MS_TEX) -> Dict[str, float]:
    """Read the fiducial broken-PL slopes from the ms.tex macros.

    Generated by Claude Fable 5 on July 17 2026.

    Args:
        ms_tex: Path to ms.tex.  On failure, FALLBACK_TARGETS is
            returned with a warning.

    Returns:
        Dict with beta1, beta1_unc, beta2, beta2_unc.
    """
    keys = {"beta1": "brokenbetaone", "beta1_unc": "brokenbetaoneunc",
            "beta2": "brokenbetatwo", "beta2_unc": "brokenbetatwounc"}
    try:
        with open(ms_tex) as f:
            text = f.read()
        out = {}
        for name, cmd in keys.items():
            m = re.search(
                r"\\newcommand\{\\" + cmd + r"\}\{([-0-9.]+)\}", text
            )
            out[name] = float(m.group(1))
        return out
    except (OSError, AttributeError):
        print(f"WARNING: could not parse {ms_tex}; using fallbacks.")
        return dict(FALLBACK_TARGETS)


def two_point_slope(
    delta1: np.ndarray, delta2: np.ndarray, lam1: float, lam2: float
) -> np.ndarray:
    """Mean log-log slope beta_obs = -dln(delta)/dln(lam) over a window.

    Generated by Claude Fable 5 on July 17 2026.

    Args:
        delta1: Depth at the short-wavelength edge lam1.
        delta2: Depth at the long-wavelength edge lam2.
        lam1: Short-wavelength window edge [micron].
        lam2: Long-wavelength window edge [micron].

    Returns:
        beta_obs, broadcast over the input arrays.
    """
    return (np.log(delta1) - np.log(delta2)) / np.log(lam2 / lam1)


def model_slopes(
    beta: np.ndarray, tau0: np.ndarray, ratio: np.ndarray
) -> Tuple[np.ndarray, np.ndarray]:
    """Blue and red effective slopes of the core-halo model.

    Generated by Claude Fable 5 on July 17 2026.

    Args:
        beta: Intrinsic opacity slope, shape (Nb, 1, 1).
        tau0: Halo optical depth at LAM_REF, shape (1, Nt, 1).
        ratio: Area ratio R = A_h/A_c, shape (1, 1, Nr).

    Returns:
        (beta_blue, beta_red), each of shape (Nb, Nt, Nr).
    """
    def depth(lam: float) -> np.ndarray:
        tau = tau0 * (lam / LAM_REF)**(-beta)
        return 1.0 + ratio * (1.0 - np.exp(-tau))
    b_blue = two_point_slope(depth(LAM_BLUE[0]), depth(LAM_BLUE[1]),
                             *LAM_BLUE)
    b_red = two_point_slope(depth(LAM_RED[0]), depth(LAM_RED[1]),
                            *LAM_RED)
    return b_blue, b_red


def run_grid(targets: Dict[str, float]) -> Dict[str, np.ndarray]:
    """Evaluate chi2 over the (beta, tau0, R) grid.

    Generated by Claude Fable 5 on July 17 2026.

    Args:
        targets: Output of parse_targets.

    Returns:
        Dict with chi2 (Nb, Nt, Nr), the three grid vectors, and the
        best-fit indices and value.
    """
    beta = BETA_GRID[:, None, None]
    tau0 = TAU0_GRID[None, :, None]
    ratio = R_GRID[None, None, :]
    b_blue, b_red = model_slopes(beta, tau0, ratio)
    chi2 = (((b_blue - targets["beta1"]) / targets["beta1_unc"])**2
            + ((b_red - targets["beta2"]) / targets["beta2_unc"])**2)
    ibest = np.unravel_index(np.argmin(chi2), chi2.shape)
    return {"chi2": chi2, "beta": BETA_GRID, "tau0": TAU0_GRID,
            "ratio": R_GRID, "ibest": ibest,
            "chi2min": float(chi2[ibest])}


def profile_1d(chi2: np.ndarray, axis_keep: int) -> np.ndarray:
    """Profile Delta-chi2 along one axis (min over the other two).

    Generated by Claude Fable 5 on July 17 2026.

    Args:
        chi2: Full chi2 cube.
        axis_keep: Axis (0, 1, or 2) to keep.

    Returns:
        Delta-chi2 vector along the kept axis.
    """
    axes = tuple(i for i in range(3) if i != axis_keep)
    return chi2.min(axis=axes) - chi2.min()


def interval(
    grid: np.ndarray, dchi2: np.ndarray, thresh: float
) -> Tuple[float, float]:
    """Range of a parameter with profile Delta-chi2 below a threshold.

    Generated by Claude Fable 5 on July 17 2026.

    Args:
        grid: Parameter grid vector.
        dchi2: Profile Delta-chi2 on that grid.
        thresh: Delta-chi2 threshold.

    Returns:
        (lo, hi) grid values bracketing the allowed range; NaNs if
        nothing is allowed.
    """
    ok = grid[dchi2 < thresh]
    if ok.size == 0:
        return (np.nan, np.nan)
    return (float(ok.min()), float(ok.max()))


def make_corner(res: Dict[str, np.ndarray], targets: Dict[str, float],
                outdir: str = OUTDIR) -> None:
    """Corner-style figure: 1-d profiles and 2-d allowed regions.

    Generated by Claude Fable 5 on July 17 2026.

    Args:
        res: Output of run_grid.
        targets: Output of parse_targets.
        outdir: Output directory.
    """
    grids = [res["beta"], res["tau0"], res["ratio"]]
    labels = [r"intrinsic $\beta$",
              rf"$\tau_h({LAM_REF}\,\mu{{\rm m}})$",
              r"$A_h/A_c$"]
    logax = [False, True, True]
    rep = [REP["beta"], REP["tau0"], REP["R"]]
    chi2 = res["chi2"]
    rmaxs = [1.0 / d - 1.0 for d in DELTA_IR]

    def overlay(ax, var: int, axis: str) -> None:
        """Draw the physical-prior lines for one panel axis.

        Generated by Claude Fable 5 on July 17 2026.

        Args:
            ax: Target axis.
            var: Variable index (0 beta, 1 tau0, 2 R).
            axis: 'x' or 'y'.
        """
        from matplotlib.colors import to_rgba
        span = ax.axvspan if axis == "x" else ax.axhspan
        line = ax.axvline if axis == "x" else ax.axhline
        if var == 0:
            span(BETA_MAX, grids[0][-1], facecolor=("C3", 0.10),
                 edgecolor=to_rgba("C3", 0.55), hatch="///", lw=0)
            line(BETA_MAX, c="C3", lw=0.8)
            line(BETA_ISM, c="C3", lw=0.8, ls=":")
        elif var == 2:
            for rmax, h in zip(rmaxs, ["\\\\\\", "\\\\"]):
                span(rmax, grids[2][-1], facecolor=("C0", 0.07),
                     edgecolor=to_rgba("C0", 0.55), hatch=h, lw=0)
                line(rmax, c="C0", lw=0.8)

    set_style('science')
    fig, axs = plt.subplots(3, 3, figsize=(7.5, 7.5))
    for i in range(3):
        for j in range(3):
            ax = axs[i, j]
            if j > i:
                ax.set_axis_off()
                continue
            if i == j:
                d1 = np.maximum(profile_1d(chi2, i), 1e-3)
                ax.plot(grids[i], d1, c="k", lw=1.2)
                for t, ls in zip(DCHI2_1D, [":", "--"]):
                    ax.axhline(t, c="gray", lw=0.7, ls=ls)
                ax.axvline(rep[i], c="C3", lw=0.9)
                overlay(ax, i, "x")
                ax.set_yscale("log")
                ax.set_ylim(3e-2, 3e2)
                ax.set_ylabel(r"$\Delta\chi^2$" if j == 0 else "")
            else:
                axk = tuple(k for k in range(3) if k not in (i, j))[0]
                d2 = np.maximum(chi2.min(axis=axk) - chi2.min(),
                                1e-3)
                # chi2 axes are (beta, tau0, R); after min over axk,
                # remaining axes are ordered (j, i) with j < i.
                xx, yy = np.meshgrid(grids[j], grids[i],
                                     indexing="ij")
                pcm = ax.pcolormesh(
                    xx, yy, d2, norm=LogNorm(vmin=1e-1, vmax=1e3),
                    cmap="Greys_r", shading="auto", rasterized=True
                )
                ax.contour(xx, yy, d2, levels=DCHI2_2D, colors="C1",
                           linewidths=0.8, linestyles=["-", "--"])
                ax.plot(rep[j], rep[i], marker="*", c="C3", ms=9,
                        mec="k", mew=0.4, ls="none")
                overlay(ax, j, "x")
                overlay(ax, i, "y")
                if logax[i]:
                    ax.set_yscale("log")
            if logax[j] and i != j:
                ax.set_xscale("log")
            if logax[j] and i == j:
                ax.set_xscale("log")
            if i == 2:
                ax.set_xlabel(labels[j])
            else:
                ax.set_xticklabels([])
            if j == 0 and i != 0:
                ax.set_ylabel(labels[i])
            elif j != 0 and i != j:
                ax.set_yticklabels([])
    fig.suptitle(
        rf"Core-halo params allowed by "
        rf"$\beta_1$={targets['beta1']}$\pm${targets['beta1_unc']}, "
        rf"$\beta_2$={targets['beta2']}$\pm${targets['beta2_unc']}"
        "\n(grayscale: profile $\\Delta\\chi^2$; orange: joint "
        "68/95%; star: representative model;\n"
        "hatched = excluded by priors -- red: $\\beta$>4 "
        r"super-Rayleigh (dotted $\beta$=2 ISM-like); "
        "blue: $A_h+A_c$>$A_\\star$ for "
        rf"$\delta_{{\rm IR}}$={DELTA_IR[0]:.0%}, {DELTA_IR[1]:.0%})",
        fontsize=9)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    cax = fig.add_axes([0.76, 0.60, 0.018, 0.24])
    cb = fig.colorbar(pcm, cax=cax)
    cb.set_label(r"profile $\Delta\chi^2$")
    os.makedirs(outdir, exist_ok=True)
    outpath = join(outdir, "allowed_core_halo_params.png")
    fig.savefig(outpath, dpi=300)
    print(f"Wrote {outpath}")


def main() -> None:
    """Run the grid, print intervals, and make the corner figure.

    Generated by Claude Fable 5 on July 17 2026.
    """
    targets = parse_targets()
    print(f"Targets: beta1 = {targets['beta1']} +/- "
          f"{targets['beta1_unc']}, beta2 = {targets['beta2']} +/- "
          f"{targets['beta2_unc']}")
    res = run_grid(targets)
    ib = res["ibest"]
    print(f"chi2_min = {res['chi2min']:.3f} at beta = "
          f"{res['beta'][ib[0]]:.2f}, tau0 = {res['tau0'][ib[1]]:.3g}"
          f", R = {res['ratio'][ib[2]]:.3g}")
    names = ["beta", "tau0", "ratio"]

    def report(chi2: np.ndarray, header: str) -> None:
        print(header)
        for i, name in enumerate(names):
            axes = tuple(k for k in range(3) if k != i)
            d1 = chi2.min(axis=axes) - chi2.min()
            for t, tag in zip(DCHI2_1D, ["68%", "95%"]):
                lo, hi = interval(res[name], d1, t)
                edge = ""
                if not np.isnan(lo):
                    gmin, gmax = res[name][0], res[name][-1]
                    if np.isclose(lo, gmin) or np.isclose(hi, gmax):
                        edge = "  [runs into grid edge]"
                print(f"  {name:>6s} {tag}: {lo:.3g} -- {hi:.3g}"
                      f"{edge}")

    report(res["chi2"], "No priors:")
    for d_ir in DELTA_IR:
        rmax = 1.0 / d_ir - 1.0
        mask = ((BETA_GRID[:, None, None] <= BETA_MAX)
                & (R_GRID[None, None, :] <= rmax))
        chi2p = np.where(mask, res["chi2"], np.inf)
        report(chi2p,
               f"With priors (beta <= {BETA_MAX:g}, A_h/A_c <= "
               f"{rmax:.3g} from delta_IR = {d_ir:.0%}):")
    make_corner(res, targets)


if __name__ == "__main__":
    main()
