"""
Quantify how significantly the single power-law extinction fit
under-predicts the largest FourStar/TESS NIR dip of TIC 300651846.

The deepest dip in the sample (TIC 300651846, 2025 Feb 10, "dip 1") was
observed simultaneously in TESS (optical) and FourStar NB2.09 (2.1 um).
Under the fitted extinction law depth ~ (lambda/lambda0)^(-beta), the
depth of a single dip in two bands scales as

    delta_NB209 / delta_TESS = (lambda_NB209 / lambda_TESS)^(-beta),

with lambda the SVO pivot wavelengths (identical convention to
complexrotators.fit_dips_beta.get_lambda_eff, so this reuses that code).
This driver:

  1. reads the two dip depths from the dip-depth CSV and forms the
     observed ratio delta_NB209/delta_TESS (with propagated error);
  2. reads the single-power-law beta (posterior mean +/- SD, both the
     no-sigma_int and with-sigma_int variants) from the "Single" row of
     results/beta_fit/combined/tab_fitresults_rows.tex;
  3. forms the predicted ratio and its beta-only uncertainty for each
     variant, and the discrepancy n_sigma = (obs - pred) / combined_err;
  4. prints the result to STDOUT and writes every value (depths, the
     observed ratio, and -- for each sigma_int variant -- the predicted
     ratio and n_sigma) as \\newcommand's into a marker-delimited,
     auto-generated block in ms.tex.

Unadorned command names (e.g. \\nunderpredictsigma) are the fiducial
with-sigma_int variant (the fit that folds intrinsic scatter into beta's
uncertainty); the "nosig" suffix denotes the no-sigma_int variant.

Usage:
    conda run -n cpv python drivers/calc_fourstar_significant.py
    (add --dry-run to print without editing ms.tex)

Generated by Claude Code on 2026-07-13.
"""
import argparse
import re
import sys
from os.path import join

import numpy as np

from complexrotators.paths import DATADIR, RESULTSDIR
from complexrotators import fit_dips_beta as fdb

# The largest dip: TIC 300651846, 2025 Feb 10, dip 1, seen in TESS and
# FourStar NB2.09.  Selected by (star, dip, band) rather than date so a
# date-string tweak in the CSV cannot silently mis-select.
STAR = "TIC 300651846"
DIP = 1
BAND_OPT = "TESS"       # blue band (denominator)
BAND_NIR = "NB2.09"     # red band (numerator)

CSV_PATH = join(
    fdb.__file__.rsplit("complexrotators", 1)[0],
    "papers", "Bouma_2026_cgcd", "tables",
    "dipdepths_thiswork_and_literature.csv",
)
SVO_DIR = join(DATADIR, "photometry", "svo_bandpasses")
FITRESULTS_TEX = join(
    RESULTSDIR, "beta_fit", "combined", "tab_fitresults_rows.tex"
)
MS_TEX = join(
    fdb.__file__.rsplit("complexrotators", 1)[0],
    "papers", "Bouma_2026_cgcd", "ms.tex",
)

# Sentinel comments delimiting the auto-generated newcommand block in
# ms.tex.  The whole span between them is rewritten each run, so the set
# of commands stays in sync with the computation and edits are
# idempotent.  On the first run (before the block exists) the driver
# migrates the pre-existing single \nunderpredictsigma line into it.
BLOCK_BEGIN = (
    "% BEGIN fourstar depth-ratio values -- auto-generated by "
    "drivers/calc_fourstar_significant.py; do not edit by hand"
)
BLOCK_END = "% END fourstar depth-ratio values"


def get_depth(df, band):
    """Return (depth_pct, depth_err_pct) for the target dip in one band.

    Generated by Claude Code on 2026-07-13.

    Args:
        df: The full dip-depth table (output of fdb.load_depths).
        band: The band string to select (e.g. "TESS", "NB2.09").

    Returns:
        Tuple (depth_pct, depth_err_pct) as floats.
    """
    sel = df[
        (df["star"] == STAR) & (df["dip"] == DIP) & (df["band"] == band)
    ]
    if len(sel) != 1:
        raise ValueError(
            f"expected exactly one {STAR} dip {DIP} {band} row, got "
            f"{len(sel)}:\n{sel}"
        )
    row = sel.iloc[0]
    return float(row["depth_pct"]), float(row["depth_err_pct"])


def parse_single_betas(tex_path):
    """Parse the two Single-model betas from tab_fitresults_rows.tex.

    The "Single" row's last two cells are the single-power-law beta as
    ``$mean\\pm sd$``, in the column order the table is written:
    no-sigma_int first, with-sigma_int second (see
    fit_dips_beta.export_fitresults_table).

    Generated by Claude Code on 2026-07-13.

    Args:
        tex_path: Path to tab_fitresults_rows.tex.

    Returns:
        Dict {"no_sigma_int": (mean, sd), "with_sigma_int": (mean, sd)}.
    """
    line = None
    with open(tex_path) as f:
        for ln in f:
            if ln.lstrip().startswith("Single &"):
                line = ln
                break
    if line is None:
        raise ValueError(f"no 'Single &' row found in {tex_path}")

    cells = line.split("&")
    pat = re.compile(r"\$\s*([-\d.]+)\s*\\pm\s*([-\d.]+)\s*\$")
    betas = []
    for cell in cells[-2:]:
        m = pat.search(cell)
        if m is None:
            raise ValueError(f"could not parse beta from cell: {cell!r}")
        betas.append((float(m.group(1)), float(m.group(2))))
    return {"no_sigma_int": betas[0], "with_sigma_int": betas[1]}


def build_block(cmds):
    """Assemble the marker-delimited newcommand block as a string.

    Generated by Claude Code on 2026-07-13.

    Args:
        cmds: Ordered list of (name, value_str, comment) tuples.

    Returns:
        The block text (BEGIN marker, one \\newcommand per command with
        an aligned trailing comment, END marker), without a trailing
        newline.
    """
    width = max(len(name) + len(val) for name, val, _ in cmds)
    lines = [BLOCK_BEGIN]
    for name, val, comment in cmds:
        cmd = r"\newcommand{\%s}{%s}" % (name, val)
        pad = " " * (width - len(name) - len(val))
        lines.append(f"{cmd}{pad}  % {comment}")
    lines.append(BLOCK_END)
    return "\n".join(lines)


def write_values_block(ms_path, cmds, dry_run=False):
    """Write the auto-generated newcommand block into ms.tex.

    Replaces the existing marker-delimited block if present; otherwise
    migrates the pre-existing single ``\\newcommand{\\nunderpredictsigma}``
    line into the new block (first-run bootstrap).  Both replacements go
    through a function so backslashes in the block (``\\newcommand`` etc.)
    are inserted literally rather than interpreted as ``re`` replacement
    escapes (``\\n`` -> newline).

    Generated by Claude Code on 2026-07-13.

    Args:
        ms_path: Path to ms.tex.
        cmds: Ordered list of (name, value_str, comment) tuples.
        dry_run: If True, do not write; just return the block.

    Returns:
        The block text that was (or would be) written.
    """
    with open(ms_path) as f:
        text = f.read()
    block = build_block(cmds)

    block_pat = re.compile(
        re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END), re.DOTALL
    )
    if block_pat.search(text):
        new_text, n = block_pat.subn(lambda _m: block, text)
    else:
        # First run: replace the pre-existing single newcommand line.
        line_pat = re.compile(
            r"\\newcommand\{\\nunderpredictsigma\}\{[^}]*\}[^\n]*"
        )
        new_text, n = line_pat.subn(lambda _m: block, text)
    if n != 1:
        raise ValueError(
            f"expected exactly one block/nunderpredictsigma anchor in "
            f"{ms_path}, replaced {n}"
        )

    if not dry_run:
        with open(ms_path, "w") as f:
            f.write(new_text)
    return block


def main(argv=None):
    """Compute the depth-ratio discrepancy and update ms.tex.

    Generated by Claude Code on 2026-07-13.

    Args:
        argv: Optional argument vector (defaults to sys.argv).

    Returns:
        Process exit code.
    """
    p = argparse.ArgumentParser(
        description="FourStar/TESS depth-ratio vs power-law prediction"
    )
    p.add_argument("--dry-run", action="store_true",
                   help="print the result without editing ms.tex")
    args = p.parse_args(argv)

    df = fdb.load_depths(CSV_PATH)

    # --- observed depth ratio (NIR / optical) ---
    d_opt, e_opt = get_depth(df, BAND_OPT)
    d_nir, e_nir = get_depth(df, BAND_NIR)
    r_obs = d_nir / d_opt
    # Independent errors: fractional errors add in quadrature.
    r_obs_err = r_obs * np.hypot(e_nir / d_nir, e_opt / d_opt)

    # --- pivot wavelengths (same convention as the beta fit) ---
    lam_opt = fdb.get_lambda_eff(
        "TESS_TESS.Red.dat", SVO_DIR, band=BAND_OPT
    ).value
    lam_nir = fdb.get_lambda_eff(
        "LCO_FourStar.NB209.dat", SVO_DIR, band=BAND_NIR
    ).value
    lam_ratio = lam_nir / lam_opt
    ln_lam_ratio = np.log(lam_ratio)

    # --- fitted betas ---
    betas = parse_single_betas(FITRESULTS_TEX)

    print("=" * 70)
    print("FourStar NB2.09 vs TESS depth ratio: largest dip of TIC 300651846")
    print("=" * 70)
    print(f"  {BAND_OPT:>7s}: depth = {d_opt:.2f} +/- {e_opt:.2f} %"
          f"   (lambda_pivot = {lam_opt:.4f} um)")
    print(f"  {BAND_NIR:>7s}: depth = {d_nir:.2f} +/- {e_nir:.2f} %"
          f"   (lambda_pivot = {lam_nir:.4f} um)")
    print(f"  lambda_NB209 / lambda_TESS = {lam_ratio:.4f}"
          f"   (ln = {ln_lam_ratio:.4f})")
    print()
    print(f"  observed ratio delta_NB209/delta_TESS = "
          f"{r_obs:.4f} +/- {r_obs_err:.4f}")
    print()
    print("  prediction: (lambda_NB209/lambda_TESS)^(-beta)")
    print("  " + "-" * 66)

    results = {}
    for tag in ("no_sigma_int", "with_sigma_int"):
        beta, beta_err = betas[tag]
        r_pred = lam_ratio ** (-beta)
        # d(ratio)/d(beta) = -ln(lam_ratio) * ratio  ->  |.|*sigma_beta.
        r_pred_err = r_pred * ln_lam_ratio * beta_err
        diff = r_obs - r_pred
        comb_err = np.hypot(r_obs_err, r_pred_err)
        n_sigma = diff / comb_err
        results[tag] = {"r_pred": r_pred, "r_pred_err": r_pred_err,
                        "n_sigma": n_sigma}
        print(f"  [{tag:>14s}] beta = {beta:.2f} +/- {beta_err:.2f}")
        print(f"  {'':>16s} predicted ratio = "
              f"{r_pred:.4f} +/- {r_pred_err:.4f}")
        print(f"  {'':>16s} (obs - pred) = {diff:+.4f}"
              f"  ->  under-predicts by {n_sigma:.2f} sigma")
        print("  " + "-" * 66)

    # Assemble the newcommand block.  Unadorned names = fiducial
    # (with_sigma_int); "nosig" suffix = no_sigma_int.  Depths/ratio at
    # 2 dp, n_sigma at 1 dp, matching how they read in the text.
    fid, nos = results["with_sigma_int"], results["no_sigma_int"]
    cmds = [
        ("fourstartessdepth", f"{d_opt:.2f}", "TESS dip depth [%]"),
        ("fourstartessdepthunc", f"{e_opt:.2f}", "TESS dip depth unc [%]"),
        ("fourstarnbdepth", f"{d_nir:.2f}", "NB2.09 dip depth [%]"),
        ("fourstarnbdepthunc", f"{e_nir:.2f}", "NB2.09 dip depth unc [%]"),
        ("fourstarobsratio", f"{r_obs:.2f}",
         "observed depth ratio NB2.09/TESS"),
        ("fourstarobsratiounc", f"{r_obs_err:.2f}",
         "observed depth ratio unc"),
        ("fourstarpredratio", f"{fid['r_pred']:.2f}",
         "predicted ratio, with sigma_int"),
        ("fourstarpredratiounc", f"{fid['r_pred_err']:.2f}",
         "predicted ratio unc, with sigma_int"),
        ("fourstarpredrationosig", f"{nos['r_pred']:.2f}",
         "predicted ratio, no sigma_int"),
        ("fourstarpredrationosigunc", f"{nos['r_pred_err']:.2f}",
         "predicted ratio unc, no sigma_int"),
        ("nunderpredictsigma", f"{fid['n_sigma']:.1f}",
         "NIR under-prediction [sigma], with sigma_int (fiducial)"),
        ("nunderpredictsigmanosig", f"{nos['n_sigma']:.1f}",
         "NIR under-prediction [sigma], no sigma_int"),
    ]

    block = write_values_block(MS_TEX, cmds, dry_run=args.dry_run)
    verb = "Would write" if args.dry_run else "Wrote"
    print()
    print(f"  {verb} {len(cmds)} newcommands to {MS_TEX}:")
    for line in block.splitlines():
        print(f"    {line}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
