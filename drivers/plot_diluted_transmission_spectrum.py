"""Transmission spectrum of a dust blob: density-profile effects.

Profiles (all with the same total mass, i.e. the same mean
projected optical depth taubar = kappa * M / (pi R^2)):
  slab      : Sigma = const
  sphere    : n = const           -> Sigma ~ sqrt(1 - x^2)
  gaussian  : n ~ exp(-r^2/2a^2)  -> Sigma ~ exp(-x^2/2w^2)
  outflow   : n ~ r^-2 (r0..R)    -> Sigma ~ arctan(sqrt(1-x^2)/x)/x
Depth D(lambda) = f(taubar * kappa-shape), kappa ~ lambda^-beta.
"""
import os
from os.path import join

import numpy as np
import matplotlib.pyplot as plt
from aesthetic.plot import set_style

if not hasattr(np, 'trapezoid'):  # numpy < 2.0
    np.trapezoid = np.trapz

try:
    from complexrotators.paths import RESULTSDIR
except ImportError:
    RESULTSDIR = join(os.path.dirname(__file__), "..", "results")

OUTDIR = join(RESULTSDIR, "diluted_transmission_spectrum")

BANDS = ['u', 'g', 'r', 'i', 'z', 'J', 'H', 'K']
LAMBDAS = np.array([0.355, 0.475, 0.622, 0.763, 0.905, 1.25,
                    1.65, 2.2])
L_TESS = 0.7865  # TESS effective wavelength [micron]
NX = 4000
X = np.linspace(1e-6, 1.0, NX)  # projected radius x = r/R
W_GAUSS = 0.3   # Gaussian Sigma width in units of R
X0_OUT = 0.01   # inner cutoff of r^-2 outflow, in units of R


def _normalize(shape: np.ndarray) -> np.ndarray:
    """Scale a Sigma shape to unit area-weighted mean.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        shape: Sigma shape evaluated on the module grid X.

    Returns:
        Shape with <s> = int s(x) 2x dx = 1 on x in [0, 1].
    """
    mean = np.trapezoid(shape * 2 * X, X)
    return shape / mean


def sigma_shape(profile: str) -> np.ndarray:
    """Normalized projected surface-density shape s(x).

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        profile: One of 'slab', 'sphere', 'gaussian', 'outflow'.

    Returns:
        s(x) on the module grid X, mass-normalized to <s> = 1.
    """
    if profile == 'slab':
        s = np.ones_like(X)
    elif profile == 'sphere':
        s = np.sqrt(1 - X**2)
    elif profile == 'gaussian':
        s = np.exp(-X**2 / (2 * W_GAUSS**2))
    elif profile == 'outflow':
        xc = np.maximum(X, X0_OUT)
        s = np.arctan(np.sqrt(np.maximum(1 - xc**2, 0)) / xc) / xc
    else:
        raise ValueError(profile)
    return _normalize(s)


def f_depth(taubar: np.ndarray, shape: np.ndarray) -> np.ndarray:
    """Covering fraction f = D / (pi R^2 / A_star).

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        taubar: Mean projected optical depth(s), kappa M/(pi R^2).
        shape: Normalized Sigma shape on grid X.

    Returns:
        f(taubar), same shape as taubar.
    """
    tb = np.atleast_1d(taubar).astype(float)
    integ = 1 - np.exp(-tb[:, None] * shape[None, :])
    return np.trapezoid(integ * 2 * X, X, axis=1)


def spectrum(taubar_t: float, beta: float, lams: np.ndarray,
             shape: np.ndarray) -> np.ndarray:
    """Transmission spectrum normalized at the TESS band.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        taubar_t: Mean optical depth at the TESS band.
        beta: Opacity index, kappa ~ lambda^-beta.
        lams: Wavelengths in micron.
        shape: Normalized Sigma shape on grid X.

    Returns:
        D(lambda) / D(TESS).
    """
    tb = taubar_t * (lams / L_TESS)**(-beta)
    return f_depth(tb, shape) / f_depth(taubar_t, shape)[0]


def sigma_map(shape: np.ndarray, npix: int = 400) -> np.ndarray:
    """Project a 1-d Sigma shape onto a face-on (x, y) image.

    Generated by Claude Fable 5 on July 16 2026.

    Args:
        shape: Normalized Sigma shape on the module grid X.
        npix: Pixels per side of the square image.

    Returns:
        (npix, npix) image of Sigma/<Sigma>; NaN outside the blob.
    """
    g = np.linspace(-1.4, 1.4, npix)
    xx, yy = np.meshgrid(g, g)
    rr = np.hypot(xx, yy)
    img = np.interp(rr, X, shape, right=np.nan)
    img[rr > 1] = np.nan
    return img


def main() -> None:
    """Make the single-column figure and print the dilution table.

    Layout (subplot_mosaic, single-column AASTeX):
      A B / C D : face-on Sigma(x, y) images of the four profiles on
                  a shared color scale (mass-matched, so brightness is
                  comparable).
      E         : chromatic dilution vs mean optical depth.
      F         : observed transmission spectra.

    Generated by Claude Fable 5 on July 16 2026.
    """
    from matplotlib.colors import Normalize

    set_style("science")

    profiles = ['slab', 'sphere', 'gaussian', 'outflow']
    labels = {
        'slab': r'slab ($\Sigma$ const)',
        'sphere': r'uniform sphere',
        'gaussian': rf'Gaussian ($w={W_GAUSS}R$)',
        'outflow': r'outflow ($n\propto r^{-2}$)',
    }
    shortlabels = {
        'slab': r'slab ($\Sigma$ const)',
        'sphere': r'uniform sphere',
        'gaussian': rf'Gaussian ($w={W_GAUSS}R$)',
        'outflow': r'outflow',
    }

    colors = dict(zip(profiles, ['C1', 'C0', 'C2', 'C3']))
    ls = dict(zip(profiles, ['--', '-', '-.', ':']))
    shapes = {p: sigma_shape(p) for p in profiles}

    fig, axd = plt.subplot_mosaic(
        """
        AB
        CD
        EE
        EE
        FF
        FF
        """,
        figsize=(2.52, 5.95), layout='constrained')

    # Panels A-D: face-on Sigma maps, shared color scale.
    im_axes = {'A': 'slab', 'B': 'sphere',
               'C': 'gaussian', 'D': 'outflow'}
    norm = Normalize(vmin=0, vmax=6)
    cmap = plt.get_cmap('gray_r').copy()  # dark = high Sigma
    cmap.set_over('black')  # outflow cusp exceeds vmax
    cmap.set_bad('white')
    th = np.linspace(0, 2 * np.pi, 200)
    for key, p in im_axes.items():
        ax = axd[key]
        im = ax.imshow(sigma_map(shapes[p]), origin='lower',
                       cmap=cmap, norm=norm,
                       extent=[-1.4, 1.4, -1.4, 1.4])
        ax.plot(np.cos(th), np.sin(th), '--', c='0.7', lw=0.8)
        ax.set_title(labels[p], color=colors[p], fontsize=7)
        ax.set_xticks([-1, 0, 1])
        ax.set_yticks([-1, 0, 1])
        ax.tick_params(labelsize=6)
        smax = np.nanmax(shapes[p])
        SHOW_TEXT = 0
        if SHOW_TEXT:
            ax.text(0.03, 0.97,
                    rf'$\Sigma_{{\max}}/\bar\Sigma={smax:.3g}$',
                    transform=ax.transAxes, va='top', fontsize=5.5,
                    bbox=dict(fc='white', ec='none', alpha=0.85,
                              pad=1.0))
    for key in ('C', 'D'):
        axd[key].set_xlabel('x / R', fontsize=7)
    for key in ('A', 'C'):
        axd[key].set_ylabel('y / R', fontsize=7)
    for key in ('A', 'B'):
        axd[key].set_xticklabels([])
    for key in ('B', 'D'):
        axd[key].set_yticklabels([])
    cb = fig.colorbar(im, ax=[axd[k] for k in ('A', 'B', 'C', 'D')],
                      location='top', fraction=0.05, pad=0.03,
                      aspect=30, shrink=0.66, extend='max')
    cb.ax.tick_params(labelsize=6)
    cb.set_label(
        r'Dust surface density, $\Sigma/\bar{\Sigma}$ '
        r'(mean-normalized)', fontsize=7)

    # Panel E: chromatic dilution vs mean optical depth.
    t = np.logspace(-2, 3, 300)
    axE = axd['E']
    for p in profiles:
        g = np.gradient(np.log(f_depth(t, shapes[p])), np.log(t))
        axE.semilogx(t, g, ls[p], c=colors[p], label=shortlabels[p])
    axE.set_xlabel(r'Mean optical depth, $\bar{\tau}$', fontsize=8)
    axE.set_ylabel(r'Dilution factor, $\beta_{\rm obs}/\beta$',
                   fontsize=8)
    axE.tick_params(labelsize=7)
    axE.legend(fontsize=6, loc='upper right')

    # Panel F: transmission spectra, beta = 2.0, taubar(TESS) = 3.
    beta, tb0 = 2, 3.0
    lam_f = np.linspace(0.33, 2.3, 200)
    axF = axd['F']
    axF.plot(lam_f, (lam_f / L_TESS)**(-beta), c='darkgray', lw=0.8,
             label=rf'limit if $\tau\ll 1$ ($\lambda^{{-{beta}}}$)', zorder=-1)
    for p in profiles:
        axF.plot(lam_f, spectrum(tb0, beta, lam_f, shapes[p]),
                 ls[p], c=colors[p], label=shortlabels[p])
    axF.set_xlabel(r'Wavelength, $\lambda$ ($\mu$m)', fontsize=8)
    axF.set_ylabel(r'$\delta\,/\,\delta_{\mathrm{TESS}}$',
                   fontsize=8)
    axF.set_ylim(0., 3.0)
    axF.tick_params(labelsize=7)
    axF.text(0.05, 0.93, rf'$\beta$={beta:g}, '
             rf'$\bar{{\tau}}_{{\mathrm{{TESS}}}}$={tb0:g}',
             transform=axF.transAxes, va='top', ha='left',
             fontsize=8,
             bbox=dict(fc='white', ec='0.6', lw=0.6, pad=2.5))
    axF.legend(fontsize=6)

    os.makedirs(OUTDIR, exist_ok=True)
    fig.savefig(join(OUTDIR, 'diluted_transmission_spectrum.png'),
                dpi=250)
    fig.savefig(join(OUTDIR, 'diluted_transmission_spectrum.pdf'))

    # Table: beta_obs/beta at TESS band.
    hdr = 'taubar(TESS)' + ''.join(f'{p:>10s}' for p in profiles)
    print(hdr)
    eps = 1e-3
    for tb in [0.1, 0.3, 1, 3, 10, 30, 100]:
        row = f'{tb:12.1f}'
        for p in profiles:
            g = ((np.log(f_depth(tb * (1 + eps), shapes[p]))
                  - np.log(f_depth(tb * (1 - eps), shapes[p])))
                 / (2 * eps))
            row += f'{g[0]:10.3f}'
        print(row)


if __name__ == '__main__':
    main()
